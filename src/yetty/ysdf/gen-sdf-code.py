def generate_sdf_yaml_factory_impl(prims: list[dict], out: Path) -> None:
    """Generate yaml-factory.gen.c - factory implementation"""
    prims_2d = [p for p in prims if p["category"] == "sdf2d"]

    lines = [HEADER_C, ""]
    lines.append('#include <yetty/ysdf/yaml-factory.gen.h>')
    lines.append('#include <yetty/ysdf/types.gen.h>')
    lines.append('#include <yetty/ydraw-core/buffer.h>')
    lines.append('#include <yetty/ydraw-yaml/ypaint-yaml.h>')
    lines.append('#include <yetty/ytrace/ytrace.h>')
    lines.append('#include <yaml.h>')
    lines.append('#include <stdlib.h>')
    lines.append('#include <string.h>')
    lines.append('#include <math.h>')
    lines.append("")

    # Color parsing helper
    lines.append("/*=============================================================================")
    lines.append(" * Helpers")
    lines.append(" *===========================================================================*/")
    lines.append("")
    lines.append("static uint32_t parse_color(const char *str) {")
    lines.append("    if (!str || !*str) return 0;")
    lines.append("    if (str[0] == '#') str++;")
    lines.append("    size_t len = strlen(str);")
    lines.append("    char buf[9] = {0};")
    lines.append("    if (len == 3) {")
    lines.append('        buf[0] = buf[1] = str[0]; buf[2] = buf[3] = str[1]; buf[4] = buf[5] = str[2]; buf[6] = buf[7] = \'F\';')
    lines.append("    } else if (len == 6) {")
    lines.append('        memcpy(buf, str, 6); buf[6] = buf[7] = \'F\';')
    lines.append("    } else if (len == 8) {")
    lines.append("        memcpy(buf, str, 8);")
    lines.append("    } else return 0;")
    lines.append("    char *end;")
    lines.append("    unsigned long v = strtoul(buf, &end, 16);")
    lines.append("    if (*end) return 0;")
    lines.append("    uint32_t r = (v >> 24) & 0xFF, g = (v >> 16) & 0xFF, b = (v >> 8) & 0xFF, a = v & 0xFF;")
    lines.append("    return (a << 24) | (b << 16) | (g << 8) | r;")
    lines.append("}")
    lines.append("")

    # Parser context structure
    lines.append("/*=============================================================================")
    lines.append(" * Parse context")
    lines.append(" *===========================================================================*/")
    lines.append("")
    lines.append("struct ysdf_parse_ctx {")
    lines.append("    char prop_key[32];")
    lines.append("    uint32_t fill_color;")
    lines.append("    uint32_t stroke_color;")
    lines.append("    float stroke_width;")

    all_args = set()
    for p in prims_2d:
        for arg in p.get("args", []):
            all_args.add(arg["name"])
    for arg in sorted(all_args):
        lines.append(f"    float {arg};")

    lines.append("    int in_array;")
    lines.append("    int array_idx;")
    lines.append("    float array_vals[8];")
    lines.append("};")
    lines.append("")

    # Store array values
    lines.append("static void store_array(struct ysdf_parse_ctx *ctx) {")
    lines.append('    const char *key = ctx->prop_key;')
    lines.append('    if (strcmp(key, "position") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->center_x = ctx->array_vals[0]; ctx->center_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "size") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->half_width = ctx->array_vals[0] / 2.0f; ctx->half_height = ctx->array_vals[1] / 2.0f;")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "start") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->start_x = ctx->array_vals[0]; ctx->start_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "end") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->end_x = ctx->array_vals[0]; ctx->end_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "vertex_a") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->vertex_a_x = ctx->array_vals[0]; ctx->vertex_a_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "vertex_b") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->vertex_b_x = ctx->array_vals[0]; ctx->vertex_b_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "vertex_c") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->vertex_c_x = ctx->array_vals[0]; ctx->vertex_c_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "radii") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->radius_x = ctx->array_vals[0]; ctx->radius_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "aperture") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->aperture_x = ctx->array_vals[0]; ctx->aperture_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append('    else if (strcmp(key, "normal") == 0 && ctx->array_idx >= 2) {')
    lines.append("        ctx->normal_x = ctx->array_vals[0]; ctx->normal_y = ctx->array_vals[1];")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Build primitive data
    lines.append("static void build_prim(struct yetty_ydraw_core_buffer *buffer,")
    lines.append("                       const char *primitive_type_name,")
    lines.append("                       struct ysdf_parse_ctx *ctx) {")
    lines.append("    float data[16];")
    lines.append("    uint32_t word_count = 0, tmp;")
    lines.append("    static uint32_t z_order = 0;")
    lines.append("")

    for i, p in enumerate(prims_2d):
        name = p["name"]
        args = p.get("args", [])
        prim_word_count = GEOMETRY_OFFSET + len(args)
        cond = "if" if i == 0 else "else if"

        lines.append(f'    {cond} (strcmp(primitive_type_name, "{name}") == 0) {{')
        lines.append(f"        tmp = YETTY_YSDF_{to_upper(name)}; memcpy(&data[0], &tmp, sizeof(tmp));")
        lines.append(f"        tmp = z_order++; memcpy(&data[1], &tmp, sizeof(tmp));")
        lines.append(f"        tmp = ctx->fill_color; memcpy(&data[2], &tmp, sizeof(tmp));")
        lines.append(f"        tmp = ctx->stroke_color; memcpy(&data[3], &tmp, sizeof(tmp));")
        lines.append(f"        data[4] = ctx->stroke_width;")
        for j, arg in enumerate(args):
            lines.append(f"        data[{GEOMETRY_OFFSET + j}] = ctx->{arg['name']};")
        lines.append(f"        word_count = {prim_word_count};")
        lines.append("    }")

    lines.append("    else {")
    lines.append("        return;")
    lines.append("    }")
    lines.append("")
    lines.append("    if (word_count > 0)")
    lines.append("        yetty_ydraw_core_buffer_add_prim(buffer, data, word_count * sizeof(float));")
    lines.append("}")
    lines.append("")

    # Factory function
    lines.append("/*=============================================================================")
    lines.append(" * Factory")
    lines.append(" *===========================================================================*/")
    lines.append("")
    lines.append("struct yetty_ycore_void_result")
    lines.append("yetty_ysdf_yaml_factory(struct yetty_ydraw_core_buffer *buffer,")
    lines.append("                        struct yaml_parser_s *yaml_parser,")
    lines.append("                        const char *primitive_type_name) {")
    lines.append("    struct ysdf_parse_ctx ctx = {0};")
    lines.append("    yaml_event_t event;")
    lines.append("    int depth = 0;")
    lines.append("    int expect_value = 0;")
    lines.append("    int done = 0;")
    lines.append("")
    lines.append("    while (!done) {")
    lines.append("        if (!yaml_parser_parse(yaml_parser, &event))")
    lines.append('            return YETTY_ERR(yetty_ycore_void, "yaml parse error");')
    lines.append("")
    lines.append("        switch (event.type) {")
    lines.append("        case YAML_MAPPING_START_EVENT:")
    lines.append("            depth++;")
    lines.append("            break;")
    lines.append("        case YAML_MAPPING_END_EVENT:")
    lines.append("            depth--;")
    lines.append("            if (depth == 0) done = 1;")
    lines.append("            break;")
    lines.append("        case YAML_SEQUENCE_START_EVENT:")
    lines.append("            ctx.in_array = 1;")
    lines.append("            ctx.array_idx = 0;")
    lines.append("            break;")
    lines.append("        case YAML_SEQUENCE_END_EVENT:")
    lines.append("            store_array(&ctx);")
    lines.append("            ctx.in_array = 0;")
    lines.append("            expect_value = 0;")
    lines.append("            break;")
    lines.append("        case YAML_SCALAR_EVENT: {")
    lines.append("            const char *val = (const char *)event.data.scalar.value;")
    lines.append("            if (ctx.in_array) {")
    lines.append("                if (ctx.array_idx < 8)")
    lines.append("                    ctx.array_vals[ctx.array_idx++] = strtof(val, NULL);")
    lines.append("            } else if (!expect_value) {")
    lines.append("                strncpy(ctx.prop_key, val, sizeof(ctx.prop_key) - 1);")
    lines.append("                expect_value = 1;")
    lines.append("            } else {")
    lines.append('                if (strcmp(ctx.prop_key, "fill") == 0)')
    lines.append("                    ctx.fill_color = parse_color(val);")
    lines.append('                else if (strcmp(ctx.prop_key, "stroke") == 0)')
    lines.append("                    ctx.stroke_color = parse_color(val);")
    lines.append('                else if (strcmp(ctx.prop_key, "stroke_width") == 0)')
    lines.append("                    ctx.stroke_width = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "radius") == 0)')
    lines.append("                    ctx.radius = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "corner_radius") == 0)')
    lines.append("                    ctx.corner_radius = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "scale") == 0)')
    lines.append("                    ctx.scale = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "num_points") == 0)')
    lines.append("                    ctx.num_points = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "inner_ratio") == 0)')
    lines.append("                    ctx.inner_ratio = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "thickness") == 0)')
    lines.append("                    ctx.thickness = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "offset") == 0)')
    lines.append("                    ctx.offset = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "width") == 0)')
    lines.append("                    ctx.width = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "radius_outer") == 0)')
    lines.append("                    ctx.radius_outer = strtof(val, NULL);")
    lines.append('                else if (strcmp(ctx.prop_key, "radius_inner") == 0)')
    lines.append("                    ctx.radius_inner = strtof(val, NULL);")
    lines.append("                expect_value = 0;")
    lines.append("            }")
    lines.append("            break;")
    lines.append("        }")
    lines.append("        default:")
    lines.append("            break;")
    lines.append("        }")
    lines.append("        yaml_event_delete(&event);")
    lines.append("    }")
    lines.append("")
    lines.append("    build_prim(buffer, primitive_type_name, &ctx);")
    lines.append("    return YETTY_OK_VOID();")
    lines.append("}")
    lines.append("")

    # Registration function
    lines.append("/*=============================================================================")
    lines.append(" * Registration")
    lines.append(" *===========================================================================*/")
    lines.append("")
    lines.append("struct yetty_ycore_void_result")
    lines.append("yetty_ysdf_register_yaml_factories(struct yetty_ydraw_yaml_parser *parser) {")
    lines.append("    struct yetty_ycore_void_result res;")
    lines.append("")
    for p in prims_2d:
        name = p["name"]
        lines.append(f'    res = yetty_ydraw_yaml_parser_register(parser, "{name}", yetty_ysdf_yaml_factory);')
        lines.append("    if (!res.ok) return res;")
        lines.append("")
    lines.append("    return YETTY_OK_VOID();")
    lines.append("}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Generated: {out}")


