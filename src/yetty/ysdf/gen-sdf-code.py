def generate_sdf_prim_impl(prims: list[dict], out: Path) -> None:
    """Generate ypaint-sdf-prim.gen.c - add function implementations for SDF primitives"""
    lines = [HEADER_C, ""]
    lines.append('#include <yetty/ysdf/funcs.gen.h>')
    lines.append('#include <string.h>')
    lines.append("")

    for p in prims:
        name = p["name"]
        args = p.get("args", [])
        word_count = GEOMETRY_OFFSET + len(args)

        lines.append(f"struct yetty_ydraw_core_id_result yetty_ysdf_add_{name}(struct yetty_ydraw_core_buffer *buf, uint32_t z_order, uint32_t fill_color, uint32_t stroke_color, float stroke_width, const struct yetty_ysdf_{name} *geom) {{")
        lines.append(f"    float data[{word_count}];")
        lines.append("    uint32_t tmp;")
        lines.append("")
        # Type
        lines.append(f"    tmp = YETTY_YSDF_{to_upper(name)};")
        lines.append("    memcpy(&data[0], &tmp, sizeof(tmp));")
        # z_order
        lines.append("    tmp = z_order;")
        lines.append("    memcpy(&data[1], &tmp, sizeof(tmp));")
        # fill_color
        lines.append("    tmp = fill_color;")
        lines.append("    memcpy(&data[2], &tmp, sizeof(tmp));")
        # stroke_color
        lines.append("    tmp = stroke_color;")
        lines.append("    memcpy(&data[3], &tmp, sizeof(tmp));")
        # stroke_width
        lines.append("    data[4] = stroke_width;")
        # Geometry args
        for i, arg in enumerate(args):
            offset = GEOMETRY_OFFSET + i
            if arg["type"] == "f32":
                lines.append(f"    data[{offset}] = geom->{arg['name']};")
            else:
                lines.append(f"    tmp = geom->{arg['name']};")
                lines.append(f"    memcpy(&data[{offset}], &tmp, sizeof(tmp));")
        lines.append("")
        lines.append(f"    return yetty_ydraw_core_buffer_add_prim(buf, data, {word_count} * sizeof(float));")
        lines.append("}")
        lines.append("")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Generated: {out}")


def generate_sdf_aabb(prims: list[dict], out: Path) -> None:
    """Generate ypaint-sdf-aabb.gen.c - AABB computation for SDF primitives"""
    lines = [HEADER_C, ""]
    lines.append('#include <yetty/ysdf/types.gen.h>')
    lines.append('#include <math.h>')
    lines.append('#include <string.h>')
    lines.append("")
    lines.append("struct rectangle_result yetty_ysdf_compute_aabb(const float *data, uint32_t word_count) {")
    lines.append("    if (!data)")
    lines.append('        return YETTY_ERR(rectangle, "data is NULL");')
    lines.append("    uint32_t type;")
    lines.append("    memcpy(&type, &data[0], sizeof(type));")
    lines.append(f"    const float *geom = data + {GEOMETRY_OFFSET};  // geometry args")
    lines.append("    float stroke_width = data[4];")
    lines.append("    float expand = stroke_width * 0.5f;")
    lines.append("    struct yetty_ycore_rectangle rect = {0};")
    lines.append("    (void)word_count;")
    lines.append("")
    lines.append("    switch ((enum yetty_ysdf_type)type) {")

    for p in prims:
        name = p["name"]
        aabb_code = p.get("aabb", {}).get("code", "").strip()
        if not aabb_code:
            aabb_code = "rect.min.x = -1e10f; rect.min.y = -1e10f; rect.max.x = 1e10f; rect.max.y = 1e10f;"
        else:
            # Replace *min_x/*min_y/*max_x/*max_y with rect.min.x etc.
            aabb_code = aabb_code.replace("*min_x", "rect.min.x")
            aabb_code = aabb_code.replace("*min_y", "rect.min.y")
            aabb_code = aabb_code.replace("*max_x", "rect.max.x")
            aabb_code = aabb_code.replace("*max_y", "rect.max.y")

        lines.append(f"    case YETTY_YSDF_{to_upper(name)}: {{")
        for line in aabb_code.split("\n"):
            lines.append(f"        {line}")
        lines.append("        break;")
        lines.append("    }")

    lines.append("    default:")
    lines.append('        return YETTY_ERR(rectangle, "unknown SDF type");')
    lines.append("    }")
    lines.append("    return YETTY_OK(rectangle, rect);")
    lines.append("}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Generated: {out}")


def generate_sdf_wgsl(prims: list[dict], out: Path) -> None:
    """Generate ypaint-sdf.gen.wgsl - WGSL SDF functions and dispatcher"""
    lines = [HEADER_WGSL, ""]

    # Generate individual SDF functions
    for p in prims:
        name = p["name"]
        args = p.get("args", [])
        shader = p.get("shader", {}).get("code", "")
        if not shader.strip():
            continue

        # Function signature with explicit params
        params = ["sample_pos: vec2<f32>"] if p["category"] == "sdf2d" else ["sample_pos: vec3<f32>"]
        for arg in args:
            wgsl_type = "f32" if arg["type"] == "f32" else "u32"
            params.append(f"{arg['name']}: {wgsl_type}")

        lines.append(f"fn sdf_{name}({', '.join(params)}) -> f32 {{")
        for line in shader.strip().split("\n"):
            lines.append(f"    {line}")
        lines.append("}")
        lines.append("")

    # Dispatcher bufferaccess — consumers bind an array<u32> called
    # `storage_buffer`. The SDF args are f32, the prim_type is u32, so we emit
    # bitcasts at access time. Keeps the generator coupled to one convention
    # (storage_buffer) instead of inventing per-consumer shims.
    def _u32(expr):
        return f"bitcast<u32>(storage_buffer[{expr}])"
    def _f32(expr):
        return f"bitcast<f32>(storage_buffer[{expr}])"

    def _arg_access(arg: dict, idx: int) -> str:
        offset = f"prim_offset + {GEOMETRY_OFFSET + idx}u"
        return _u32(offset) if arg["type"] != "f32" else _f32(offset)

    # Generate dispatcher for 2D
    sdf2d = [p for p in prims if p["category"] == "sdf2d"]
    if sdf2d:
        lines.append("fn evaluate_sdf_2d(prim_offset: u32, sample_pos: vec2<f32>) -> f32 {")
        lines.append(f"    let prim_type = {_u32('prim_offset')};")
        lines.append("    switch (prim_type) {")
        for p in sdf2d:
            name = p["name"]
            args = p.get("args", [])
            arg_accesses = [_arg_access(arg, i) for i, arg in enumerate(args)]
            lines.append(f"        case {wire_lit(p)}: {{ return sdf_{name}(sample_pos, {', '.join(arg_accesses)}); }}")
        lines.append("        default: { return 1e10; }")
        lines.append("    }")
        lines.append("}")
        lines.append("")

    # Generate dispatcher for 3D
    sdf3d = [p for p in prims if p["category"] == "sdf3d"]
    if sdf3d:
        lines.append("fn evaluate_sdf_3d(prim_offset: u32, sample_pos: vec3<f32>) -> f32 {")
        lines.append(f"    let prim_type = {_u32('prim_offset')};")
        lines.append("    switch (prim_type) {")
        for p in sdf3d:
            name = p["name"]
            args = p.get("args", [])
            arg_accesses = [_arg_access(arg, i) for i, arg in enumerate(args)]
            lines.append(f"        case {wire_lit(p)}: {{ return sdf_{name}(sample_pos, {', '.join(arg_accesses)}); }}")
        lines.append("        default: { return 1e10; }")
        lines.append("    }")
        lines.append("}")
        lines.append("")

    # Style extraction
    lines.append("fn get_sdf_prim_style(prim_offset: u32) -> vec3<u32> {")
    lines.append("    return vec3<u32>(")
    lines.append(f"        {_u32('prim_offset + 2u')},  // fill_color")
    lines.append(f"        {_u32('prim_offset + 3u')},  // stroke_color")
    lines.append(f"        {_u32('prim_offset + 4u')}   // stroke_width as bits")
    lines.append("    );")
    lines.append("}")
    lines.append("")

    # =========================================================================
    # Gradient evaluation: emitted only for primitives whose name starts with
    # "linear_gradient_" or "radial_gradient_". Each one's args layout follows
    # the convention: geometry first, then 4 (linear) or 3 (radial) gradient-
    # geometry floats, then 2 colors as u32.
    # =========================================================================

    def is_linear_gradient(p):
        return p["name"].startswith("linear_gradient_")

    def is_radial_gradient(p):
        return p["name"].startswith("radial_gradient_")

    def is_any_gradient(p):
        return is_linear_gradient(p) or is_radial_gradient(p)

    grads_2d = [p for p in sdf2d if is_any_gradient(p)]

    lines.append("fn yetty_ysdf_is_gradient_2d(prim_type: u32) -> bool {")
    if grads_2d:
        lines.append("    switch (prim_type) {")
        for p in grads_2d:
            lines.append(f"        case {wire_lit(p)}: {{ return true; }}")
        lines.append("        default: { return false; }")
        lines.append("    }")
    else:
        lines.append("    return false;")
    lines.append("}")
    lines.append("")

    # Fallback unpack if the consumer hasn't defined one. Matches
    # ypaint-layer.wgsl's ypaint_unpack_color (RGBA in low->high bytes).
    lines.append("fn yetty_ysdf_unpack_color(packed: u32) -> vec4<f32> {")
    lines.append("    return vec4<f32>(")
    lines.append("        f32(packed & 0xFFu) / 255.0,")
    lines.append("        f32((packed >> 8u) & 0xFFu) / 255.0,")
    lines.append("        f32((packed >> 16u) & 0xFFu) / 255.0,")
    lines.append("        f32((packed >> 24u) & 0xFFu) / 255.0,")
    lines.append("    );")
    lines.append("}")
    lines.append("")

    lines.append("fn yetty_ysdf_eval_gradient_color_2d(prim_offset: u32, sample_pos: vec2<f32>) -> vec4<f32> {")
    lines.append(f"    let prim_type = {_u32('prim_offset')};")
    lines.append("    switch (prim_type) {")
    for p in grads_2d:
        args = p.get("args", [])
        # Find argument indices by name so the layout stays in lockstep with YAML.
        idx = {arg["name"]: GEOMETRY_OFFSET + i for i, arg in enumerate(args)}
        def f32_at(name):
            return _f32(f"prim_offset + {idx[name]}u")
        def u32_at(name):
            return _u32(f"prim_offset + {idx[name]}u")
        lines.append(f"        case {wire_lit(p)}: {{")
        if is_linear_gradient(p):
            lines.append(f"            let g0 = vec2<f32>({f32_at('grad_x0')}, {f32_at('grad_y0')});")
            lines.append(f"            let g1 = vec2<f32>({f32_at('grad_x1')}, {f32_at('grad_y1')});")
            lines.append(f"            let c0 = yetty_ysdf_unpack_color({u32_at('color0')});")
            lines.append(f"            let c1 = yetty_ysdf_unpack_color({u32_at('color1')});")
            lines.append("            let dir = g1 - g0;")
            lines.append("            let len2 = dot(dir, dir);")
            lines.append("            let t = select(0.0, clamp(dot(sample_pos - g0, dir) / len2, 0.0, 1.0), len2 > 0.0);")
            lines.append("            return mix(c0, c1, t);")
        else:  # radial
            lines.append(f"            let gc = vec2<f32>({f32_at('grad_cx')}, {f32_at('grad_cy')});")
            lines.append(f"            let gr = {f32_at('grad_radius')};")
            lines.append(f"            let ci = yetty_ysdf_unpack_color({u32_at('color_inner')});")
            lines.append(f"            let co = yetty_ysdf_unpack_color({u32_at('color_outer')});")
            lines.append("            let t = select(0.0, clamp(length(sample_pos - gc) / gr, 0.0, 1.0), gr > 0.0);")
            lines.append("            return mix(ci, co, t);")
        lines.append("        }")
    lines.append("        default: { return vec4<f32>(0.0); }")
    lines.append("    }")
    lines.append("}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Generated: {out}")


def infer_yaml_props(args: list[dict]) -> list[tuple[str, str, list[str], str]]:
    """Infer YAML property mappings from arg names.
    Returns list of (yaml_key, type, [arg_names], transform)
    type: vec2, scalar, size (divides by 2)
    """
    arg_names = [a["name"] for a in args]
    props = []

    # Position patterns
    if "center_x" in arg_names and "center_y" in arg_names:
        props.append(("position", "vec2", ["center_x", "center_y"], ""))
    if "vertex_a_x" in arg_names and "vertex_a_y" in arg_names:
        props.append(("vertex_a", "vec2", ["vertex_a_x", "vertex_a_y"], ""))
        props.append(("vertex_b", "vec2", ["vertex_b_x", "vertex_b_y"], ""))
        if "vertex_c_x" in arg_names:
            props.append(("vertex_c", "vec2", ["vertex_c_x", "vertex_c_y"], ""))
    if "start_x" in arg_names and "start_y" in arg_names:
        props.append(("start", "vec2", ["start_x", "start_y"], ""))
        props.append(("end", "vec2", ["end_x", "end_y"], ""))

    # Size patterns
    if "half_width" in arg_names and "half_height" in arg_names:
        props.append(("size", "size", ["half_width", "half_height"], "/ 2.0f"))

    # Radius patterns
    if "radius" in arg_names:
        props.append(("radius", "scalar", ["radius"], ""))
    if "radius_x" in arg_names and "radius_y" in arg_names:
        props.append(("radii", "vec2", ["radius_x", "radius_y"], ""))
    if "radius_outer" in arg_names and "radius_inner" in arg_names:
        props.append(("radius_outer", "scalar", ["radius_outer"], ""))
        props.append(("radius_inner", "scalar", ["radius_inner"], ""))

    # Other scalars
    if "corner_radius" in arg_names:
        props.append(("corner_radius", "scalar", ["corner_radius"], ""))
    if "scale" in arg_names:
        props.append(("scale", "scalar", ["scale"], ""))
    if "num_points" in arg_names:
        props.append(("num_points", "scalar", ["num_points"], ""))
    if "inner_ratio" in arg_names:
        props.append(("inner_ratio", "scalar", ["inner_ratio"], ""))
    if "thickness" in arg_names:
        props.append(("thickness", "scalar", ["thickness"], ""))
    if "offset" in arg_names:
        props.append(("offset", "scalar", ["offset"], ""))
    if "width" in arg_names:
        props.append(("width", "scalar", ["width"], ""))

    return props


