HEADER_C = """// Auto-generated from sdf-primitives.yaml - DO NOT EDIT
// Generated by: src/yetty/ysdf/gen-sdf-code.py
"""

HEADER_WGSL = """// Auto-generated from sdf-primitives.yaml - DO NOT EDIT
// Generated by: src/yetty/ysdf/gen-sdf-code.py
"""

# Buffer layout (in 32-bit words):
# [0] type (enum ysdf_type value)
# [1] z_order
# [2] fill_color
# [3] stroke_color
# [4] stroke_width
# [5+] geometry args

GEOMETRY_OFFSET = 5

# Tier base for SDF wire IDs. The YAML's `type:` field is the per-tier slot
# (0..N); the actual wire / dispatch id is SDF_TIER_BASE | slot. The space
# layout for ypaint primitive types is:
#     [0x00000000, 0x0000FFFF]  cmds
#     [0x10000000, 0x1FFFFFFF]  SDF                    ← this generator
#     [0x40000000, 0x7FFFFFFF]  flyweight (FONT, TEXT_SPAN)
#     [0x80000000, 0xFFFFFFFF]  complex
SDF_TIER_BASE = 0x10000000


def wire_id(p):
    """Wire/dispatch id for a primitive: SDF tier base OR'd with the YAML slot."""
    return SDF_TIER_BASE | p["type"]


def wire_lit(p):
    """Wire id formatted as a hex C/WGSL literal (with `u` suffix)."""
    return f"0x{wire_id(p):08X}u"


def to_upper(name: str) -> str:
    """snake_case -> UPPER_SNAKE_CASE"""
    return name.upper()


def c_type(yaml_type: str) -> str:
    """Convert YAML type to C type"""
    return {"f32": "float", "u32": "uint32_t", "i32": "int32_t"}[yaml_type]


def load_primitives(path: Path) -> list[dict]:
    with open(path) as f:
        return yaml.safe_load(f)


def generate_sdf_types(prims: list[dict], out: Path) -> None:
    """Generate ypaint-sdf-types.gen.h - enums and geometry structs for SDF primitives"""
    lines = [HEADER_C, "#pragma once", "", "#include <stddef.h>", "#include <stdint.h>", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]

    # Enum for SDF primitive types. Values are the WIRE ids (tier-base | slot).
    lines.append("enum yetty_ysdf_type {")
    for p in prims:
        lines.append(f"    YETTY_YSDF_{to_upper(p['name'])} = {wire_lit(p)},")
    lines.append("};")
    lines.append("")

    # Geometry structs for each SDF primitive
    for p in prims:
        name = p["name"]
        args = p.get("args", [])

        lines.append(f"struct yetty_ysdf_{name} {{")
        for arg in args:
            lines.append(f"    {c_type(arg['type'])} {arg['name']};")
        lines.append("};")
        lines.append("")

    # Word count for each SDF primitive type
    lines.append("// Word count per SDF primitive type")
    lines.append("static inline uint32_t yetty_ysdf_word_count(enum yetty_ysdf_type type) {")
    lines.append("    switch (type) {")
    for p in prims:
        name = p["name"]
        args = p.get("args", [])
        word_count = GEOMETRY_OFFSET + len(args)
        lines.append(f"        case YETTY_YSDF_{to_upper(name)}: return {word_count}u;")
    lines.append("        default: return 0u;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Primitive size in bytes (callback compatible)
    lines.append("// Primitive size in bytes - use as yetty_ydraw_core_primitive_size_fn callback")
    lines.append("static inline size_t yetty_ysdf_primitive_size(uint32_t type) {")
    lines.append("    return yetty_ysdf_word_count((enum yetty_ysdf_type)type) * sizeof(float);")
    lines.append("}")
    lines.append("")

    # AABB computation function declaration
    lines.append("// Compute AABB for an SDF primitive")
    lines.append("// data: full primitive data (type + z_order + style + geometry)")
    lines.append("// word_count: number of 32-bit words in data")
    lines.append("#include <yetty/ycore/types.h>")
    lines.append("")
    lines.append("struct rectangle_result yetty_ysdf_compute_aabb(const float *data, uint32_t word_count);")
    lines.append("")

    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Generated: {out}")


