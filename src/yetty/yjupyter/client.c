/*
 * yjupyter:client — the live Jupyter Server connection: REST over libcurl to
 * create/delete a kernel, and a minimal RFC 6455 WebSocket client (plaintext,
 * JSON text frames — the protocol jupyter_server speaks when no binary
 * subprotocol is negotiated) to carry the v5 messages built by yjupyter:session.
 *
 * Synchronous by design: REST is a blocking libcurl easy handle; the WebSocket
 * is a blocking socket with poll()-based read timeouts. No event loop, so it is
 * driven with an explicit poll() loop and is directly testable against a real
 * kernel on loopback.
 *
 * The public interface is generated by yclass codegen from the annotations
 * below — never hand-write client.h.
 */

