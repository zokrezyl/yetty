/*=============================================================================
 * REST over libcurl
 *===========================================================================*/

struct curl_sink {
    char *data;
    size_t len;
    size_t cap;
};

static size_t curl_collect(void *ptr, size_t size, size_t nmemb, void *userdata)
{
    struct curl_sink *sink = userdata;
    size_t add = size * nmemb;
    if (sink->len + add + 1 > sink->cap) {
        size_t new_cap = sink->cap ? sink->cap * 2 : 1024;
        while (new_cap < sink->len + add + 1) {
            new_cap *= 2;
        }
        char *grown = realloc(sink->data, new_cap);
        if (!grown) {
            return 0;
        }
        sink->data = grown;
        sink->cap = new_cap;
    }
    memcpy(sink->data + sink->len, ptr, add);
    sink->len += add;
    sink->data[sink->len] = 0;
    return add;
}

/* Perform an HTTP request. On success returns the owned response body (caller
 * frees) and writes the HTTP status to *status. */
static struct yetty_ycore_char_ptr_result http_do(const char *method, const char *url,
                                                  const char *token, const char *body, long *status)
{
    CURL *curl = curl_easy_init();
    if (!curl) {
        return YETTY_ERR(yetty_ycore_char_ptr, "http_do: curl init failed");
    }

    struct curl_sink sink = {0};
    struct curl_slist *headers = NULL;
    char auth[512];
    if (token && token[0]) {
        snprintf(auth, sizeof(auth), "Authorization: token %s", token);
        headers = curl_slist_append(headers, auth);
    }
    if (body) {
        headers = curl_slist_append(headers, "Content-Type: application/json");
    }

    curl_easy_setopt(curl, CURLOPT_URL, url);
    curl_easy_setopt(curl, CURLOPT_HTTPHEADER, headers);
    curl_easy_setopt(curl, CURLOPT_WRITEFUNCTION, curl_collect);
    curl_easy_setopt(curl, CURLOPT_WRITEDATA, &sink);
    curl_easy_setopt(curl, CURLOPT_TIMEOUT, 30L);
    if (strcmp(method, "POST") == 0) {
        curl_easy_setopt(curl, CURLOPT_POST, 1L);
        curl_easy_setopt(curl, CURLOPT_POSTFIELDS, body ? body : "");
    } else if (strcmp(method, "DELETE") == 0) {
        curl_easy_setopt(curl, CURLOPT_CUSTOMREQUEST, "DELETE");
    }

    CURLcode rc = curl_easy_perform(curl);
    long code = 0;
    curl_easy_getinfo(curl, CURLINFO_RESPONSE_CODE, &code);
    curl_slist_free_all(headers);
    curl_easy_cleanup(curl);

    if (rc != CURLE_OK) {
        free(sink.data);
        return YETTY_ERR(yetty_ycore_char_ptr, "http_do: request failed");
    }
    if (status) {
        *status = code;
    }
    if (!sink.data) {
        sink.data = strdup("");
    }
    if (!sink.data) {
        return YETTY_ERR(yetty_ycore_char_ptr, "http_do: alloc failed");
    }
    return YETTY_OK(yetty_ycore_char_ptr, sink.data);
}

/*=============================================================================
 * Minimal RFC 6455 WebSocket client (plaintext)
 *===========================================================================*/

static long now_ms(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (long)ts.tv_sec * 1000 + ts.tv_nsec / 1000000;
}

static int send_all(int fd, const uint8_t *buf, size_t len)
{
    size_t sent = 0;
    while (sent < len) {
        ssize_t wrote = send(fd, buf + sent, len - sent, 0);
        if (wrote <= 0) {
            return -1;
        }
        sent += (size_t)wrote;
    }
    return 0;
}

static int read_n(int fd, uint8_t *buf, size_t len, long deadline)
{
    size_t got = 0;
    while (got < len) {
        long remaining = deadline - now_ms();
        if (remaining <= 0) {
            return -1;
        }
        struct pollfd pfd = {.fd = fd, .events = POLLIN};
        int pr = poll(&pfd, 1, (int)remaining);
        if (pr <= 0) {
            return -1;
        }
        ssize_t r = recv(fd, buf + got, len - got, 0);
        if (r <= 0) {
            return -1;
        }
        got += (size_t)r;
    }
    return 0;
}

/* Send one masked client frame. */
static int ws_send_frame(int fd, uint8_t opcode, const uint8_t *payload, size_t len)
{
    uint8_t header[14];
    size_t h = 0;
    header[h++] = (uint8_t)(0x80 | opcode);
    const uint8_t mask[4] = {0x21, 0x9a, 0x43, 0xf0};
    if (len < 126) {
        header[h++] = (uint8_t)(0x80 | len);
    } else if (len < 65536) {
        header[h++] = 0x80 | 126;
        header[h++] = (uint8_t)((len >> 8) & 0xff);
        header[h++] = (uint8_t)(len & 0xff);
    } else {
        header[h++] = 0x80 | 127;
        for (int i = 7; i >= 0; i--) {
            header[h++] = (uint8_t)((len >> (8 * i)) & 0xff);
        }
    }
    memcpy(header + h, mask, 4);
    h += 4;
    if (send_all(fd, header, h)) {
        return -1;
    }
    if (len) {
        uint8_t *masked = malloc(len);
        if (!masked) {
            return -1;
        }
        for (size_t i = 0; i < len; i++) {
            masked[i] = payload[i] ^ mask[i & 3];
        }
        int rc = send_all(fd, masked, len);
        free(masked);
        return rc;
    }
    return 0;
}

static int ws_send_text(int fd, const char *text)
{
    return ws_send_frame(fd, 0x1, (const uint8_t *)text, strlen(text));
}

/* Receive one complete text message (reassembling fragments). Returns an owned
 * NUL-terminated string, or NULL on timeout/close/error. Replies to pings. */
static char *ws_recv_text(int fd, int timeout_ms, int *out_closed)
{
    long deadline = now_ms() + timeout_ms;
    uint8_t *acc = NULL;
    size_t acc_len = 0;

    for (;;) {
        uint8_t header[2];
        if (read_n(fd, header, 2, deadline)) {
            free(acc);
            return NULL;
        }
        int fin = header[0] & 0x80;
        int opcode = header[0] & 0x0f;
        uint64_t len = header[1] & 0x7f;
        if (len == 126) {
            uint8_t ext[2];
            if (read_n(fd, ext, 2, deadline)) {
                free(acc);
                return NULL;
            }
            len = ((uint64_t)ext[0] << 8) | ext[1];
        } else if (len == 127) {
            uint8_t ext[8];
            if (read_n(fd, ext, 8, deadline)) {
                free(acc);
                return NULL;
            }
            len = 0;
            for (int i = 0; i < 8; i++) {
                len = (len << 8) | ext[i];
            }
        }

        uint8_t *payload = len ? malloc(len) : NULL;
        if (len && !payload) {
            free(acc);
            return NULL;
        }
        if (len && read_n(fd, payload, len, deadline)) {
            free(payload);
            free(acc);
            return NULL;
        }

        if (opcode == 0x8) { /* close */
            free(payload);
            free(acc);
            if (out_closed) {
                *out_closed = 1;
            }
            return NULL;
        }
        if (opcode == 0x9) { /* ping -> pong */
            ws_send_frame(fd, 0xA, payload, len);
            free(payload);
            continue;
        }
        if (opcode == 0xA) { /* pong */
            free(payload);
            continue;
        }

        /* text (0x1) or continuation (0x0) */
        uint8_t *grown = realloc(acc, acc_len + len + 1);
        if (!grown) {
            free(payload);
            free(acc);
            return NULL;
        }
        acc = grown;
        if (len) {
            memcpy(acc + acc_len, payload, len);
        }
        acc_len += len;
        free(payload);
        if (fin) {
            acc[acc_len] = 0;
            return (char *)acc;
        }
    }
}

/* Split "http://host:port" into host and port (defaulting port to 80). */
static void parse_base_url(const char *base_url, char *host, size_t host_cap, char *port,
                           size_t port_cap)
{
    const char *cursor = base_url;
    if (strncmp(cursor, "http://", 7) == 0) {
        cursor += 7;
    } else if (strncmp(cursor, "https://", 8) == 0) {
        cursor += 8;
    }
    const char *colon = strchr(cursor, ':');
    const char *slash = strchr(cursor, '/');
    const char *host_end = colon ? colon : (slash ? slash : cursor + strlen(cursor));
    size_t host_len = (size_t)(host_end - cursor);
    if (host_len >= host_cap) {
        host_len = host_cap - 1;
    }
    memcpy(host, cursor, host_len);
    host[host_len] = 0;
    if (colon) {
        const char *port_start = colon + 1;
        const char *port_end = slash ? slash : port_start + strlen(port_start);
        size_t port_len = (size_t)(port_end - port_start);
        if (port_len >= port_cap) {
            port_len = port_cap - 1;
        }
        memcpy(port, port_start, port_len);
        port[port_len] = 0;
    } else {
        snprintf(port, port_cap, "80");
    }
}

/* Open a TCP connection and perform the WebSocket upgrade handshake. */
static int ws_connect(const char *host, const char *port, const char *path, const char *token)
{
    struct addrinfo hints = {0};
    hints.ai_family = AF_UNSPEC;
    hints.ai_socktype = SOCK_STREAM;
    struct addrinfo *result = NULL;
    if (getaddrinfo(host, port, &hints, &result) != 0) {
        return -1;
    }

    int fd = -1;
    for (struct addrinfo *ai = result; ai; ai = ai->ai_next) {
        fd = socket(ai->ai_family, ai->ai_socktype, ai->ai_protocol);
        if (fd < 0) {
            continue;
        }
        if (connect(fd, ai->ai_addr, ai->ai_addrlen) == 0) {
            break;
        }
        close(fd);
        fd = -1;
    }
    freeaddrinfo(result);
    if (fd < 0) {
        return -1;
    }

    char request[2048];
    int n = snprintf(request, sizeof(request),
                     "GET %s HTTP/1.1\r\n"
                     "Host: %s:%s\r\n"
                     "Upgrade: websocket\r\n"
                     "Connection: Upgrade\r\n"
                     "Sec-WebSocket-Key: dGhlIHNhbXBsZSBub25jZQ==\r\n"
                     "Sec-WebSocket-Version: 13\r\n"
                     "Authorization: token %s\r\n"
                     "\r\n",
                     path, host, port, token ? token : "");
    if (n <= 0 || send_all(fd, (const uint8_t *)request, (size_t)n)) {
        close(fd);
        return -1;
    }

    /* Read the handshake response byte-by-byte up to the blank line, so we do
     * not consume any WebSocket frame bytes that follow it. */
    char response[2048];
    size_t used = 0;
    long deadline = now_ms() + 10000;
    while (used < sizeof(response) - 1) {
        uint8_t byte;
        if (read_n(fd, &byte, 1, deadline)) {
            close(fd);
            return -1;
        }
        response[used++] = (char)byte;
        if (used >= 4 && memcmp(response + used - 4, "\r\n\r\n", 4) == 0) {
            break;
        }
    }
    response[used] = 0;
    if (!strstr(response, " 101 ")) {
        close(fd);
        return -1;
    }
    return fd;
}

