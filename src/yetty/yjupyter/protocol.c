/*=============================================================================
 * session helpers
 *===========================================================================*/

static struct yetty_ycore_void_result session_record(struct yetty_yjupyter_session *session,
                                                     const char *msg_id, const char *tag)
{
    if (session->pending_count == session->pending_cap) {
        size_t new_cap = session->pending_cap ? session->pending_cap * 2 : 8;
        struct yjupyter_pending *grown = realloc(session->pending, new_cap * sizeof(*grown));
        if (!grown) {
            return YETTY_ERR(yetty_ycore_void, "session_record: pending grow failed");
        }
        session->pending = grown;
        session->pending_cap = new_cap;
    }
    char *msg_id_copy = strdup(msg_id);
    char *tag_copy = strdup(tag);
    if (!msg_id_copy || !tag_copy) {
        free(msg_id_copy);
        free(tag_copy);
        return YETTY_ERR(yetty_ycore_void, "session_record: dup failed");
    }
    session->pending[session->pending_count].msg_id = msg_id_copy;
    session->pending[session->pending_count].tag = tag_copy;
    session->pending_count++;
    return YETTY_OK_VOID();
}

