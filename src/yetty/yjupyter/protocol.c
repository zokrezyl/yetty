/*
 * yjupyter protocol layer — the Jupyter v5 messaging wire, as yclass classes.
 *
 *   yjupyter:message  — one Jupyter message (the JSON WebSocket frame:
 *                       {header, parent_header, metadata, content, channel}).
 *                       Build a request, encode/decode the frame, inspect it.
 *   yjupyter:session  — a client session: session id + monotonic msg-id
 *                       generation, request->tag correlation keyed on the
 *                       reply's parent_header.msg_id, and kernel busy/idle
 *                       state tracked from IOPub `status` messages.
 *
 * This is the transport-independent protocol core (the design's "encode/decode
 * ... correlate replies with requests ... track kernel busy/idle" surface). It
 * rides over a WebSocket to Jupyter Server; the live socket I/O is a separate
 * boundary above this layer. Output routing never binds to a "currently
 * executing" cell — a reply belongs to the request whose msg_id equals its
 * parent_header.msg_id (see docs/ynotebook.md).
 *
 * The public interface is generated by yclass codegen from the annotations
 * below — never hand-write protocol.h. yyjson is used internally; the public
 * methods take and return JSON text, keeping the codec out of the header.
 */

