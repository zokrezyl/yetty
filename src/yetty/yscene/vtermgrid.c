/*
 * vtermgrid.c — the independent yscene client terminal grid: class@yscene:vtermgrid.
 *
 * The Yetty-side (client) end of an ymux attachment (#699). It owns its OWN
 * libvterm instance, driven through the public SCREEN layer, and exposes the
 * resulting bounded cell grid to a dedicated packed cell-grid GPU pass. It is
 * a plain classical terminal endpoint: bytes in (ordinary terminal output —
 * text + escape/control sequences, tmux-style redraw), a cell grid out. No
 * history, no session authority, no rich content — those live elsewhere.
 *
 * This is NOT yvterm and does not reuse, wrap, extract, or link yvterm. It is
 * an independent libvterm consumer built fresh for yscene, and it is DOM-free:
 * cells never become DOM nodes or generic scene records.
 *
 * The public header (include/yetty/api/yscene/vtermgrid.h) is generated by
 * codegen from the annotations here.
 */
