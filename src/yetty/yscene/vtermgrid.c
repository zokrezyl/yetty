/* Lazily bring the blink timer up (first pack that sees a blink cell). A
 * failure leaves blink frozen visible — cosmetic, so absorbed with a debug
 * note rather than failing the pack. */
static void vtermgrid_blink_ensure_timer(struct yetty_yscene_vtermgrid *grid)
{
    if (grid->blink_timer_running || !grid->event_loop) {
        return;
    }
    struct yetty_yevent_event_loop *loop = grid->event_loop;
    struct yetty_yevent_timer_id_result timer_res = loop->ops->create_timer(loop);
    if (YETTY_IS_ERR(timer_res)) {
        yetty_ycore_error_destroy(timer_res.error);
        return;
    }
    grid->blink_timer = timer_res.value;
    grid->blink_listener.handler = vtermgrid_blink_on_tick;
    struct yetty_ycore_void_result config_res =
        loop->ops->config_timer(loop, grid->blink_timer, 530 /* ms, tmux-ish cadence */);
    struct yetty_ycore_void_result register_res =
        YETTY_IS_OK(config_res)
            ? loop->ops->register_timer_listener(loop, grid->blink_timer, &grid->blink_listener)
            : config_res;
    struct yetty_ycore_void_result start_res =
        YETTY_IS_OK(register_res) ? loop->ops->start_timer(loop, grid->blink_timer) : register_res;
    if (YETTY_IS_ERR(start_res)) {
        ydebug("vtermgrid: blink timer setup failed: %s",
               start_res.error.msg ? start_res.error.msg : "unknown");
        yetty_ycore_error_destroy(start_res.error);
        struct yetty_ycore_void_result destroy_res =
            loop->ops->destroy_timer(loop, grid->blink_timer);
        if (YETTY_IS_ERR(destroy_res)) {
            yetty_ycore_error_destroy(destroy_res.error);
        }
        return;
    }
    grid->blink_timer_running = 1;
}

static struct yetty_ycore_void_result vtermgrid_gpu_pack_and_upload(
    struct yetty_yscene_vtermgrid *grid)
{
    size_t cells = (size_t)grid->rows * grid->cols;
    if (cells == 0) {
        return YETTY_OK_VOID();
    }
    size_t words = cells * YETTY_YSCENE_VTERMGRID_WORDS_PER_CELL;
    if (grid->pack_scratch_cells < cells) {
        uint32_t *grown = realloc(grid->pack_scratch, words * sizeof(uint32_t));
        if (!grown) {
            return YETTY_ERR(yetty_ycore_void, "vtermgrid: pack scratch alloc");
        }
        grid->pack_scratch = grown;
        grid->pack_scratch_cells = cells;
    }

    int saw_blink_cell = 0;
    for (uint32_t row = 0; row < grid->rows; ++row) {
        for (uint32_t col = 0; col < grid->cols; ++col) {
            struct yetty_yscene_vtermgrid_cell cell;
            vtermgrid_read_cell(grid, row, col, &cell);

            int cell_blinks = (cell.attrs & YETTY_YSCENE_VTERMGRID_ATTR_BLINK) != 0;
            if (cell_blinks) {
                saw_blink_cell = 1;
            }
            uint32_t slot = 0;
            uint32_t cell_face = 0;
            /* Hidden blink phase: keep the cell's bg but pack a blank glyph. */
            if (cell.width != 0 && cell.glyph != 0 &&
                (cell.attrs & YETTY_YSCENE_VTERMGRID_ATTR_CONCEAL) == 0 &&
                !(cell_blinks && grid->blink_phase)) {
                struct uint32_result idx = grid->font->ops->get_glyph_index(grid->font, cell.glyph);
                if (YETTY_IS_OK(idx)) {
                    slot = idx.value;
                } else {
                    yetty_ycore_error_destroy(idx.error);
                    slot = 0xFFFFFFFFu; /* notdef / tofu */
                    /* FALLBACK face (#89): the raster chain covers what the
                     * MSDF base misses (CJK etc.); its cluster lookup bakes
                     * the combining marks into ONE slot. */
                    if (grid->fallback_font) {
                        struct yetty_yfont_ms_font *fallback = grid->fallback_font;
                        struct uint32_result fb_idx;
                        const struct yetty_yscene_vtermgrid_store_cell *fb_stored = NULL;
                        if (row < vtermgrid_active_store(grid)->rows &&
                            col < vtermgrid_active_store(grid)->cols) {
                            fb_stored =
                                &vtermgrid_active_store(grid)
                                     ->cells[(size_t)row * vtermgrid_active_store(grid)->cols +
                                             col];
                        }
                        if (fb_stored && fb_stored->mark_count > 0 &&
                            fallback->ops->get_glyph_index_cluster) {
                            fb_idx = fallback->ops->get_glyph_index_cluster(
                                fallback, cell.glyph, fb_stored->marks, fb_stored->mark_count,
                                YETTY_YFONT_MS_STYLE_REGULAR);
                        } else {
                            fb_idx = fallback->ops->get_glyph_index(fallback, cell.glyph);
                        }
                        if (YETTY_IS_OK(fb_idx)) {
                            slot = fb_idx.value;
                            cell_face = 1;
                        } else {
                            yetty_ycore_error_destroy(fb_idx.error);
                        }
                    }
                }
            }

            uint32_t fr = cell.fg & 0xFFu, fg = (cell.fg >> 8) & 0xFFu,
                     fb = (cell.fg >> 16) & 0xFFu;
            uint32_t br = cell.bg & 0xFFu, bgc = (cell.bg >> 8) & 0xFFu,
                     bb = (cell.bg >> 16) & 0xFFu;
            size_t base = ((size_t)row * grid->cols + col) * YETTY_YSCENE_VTERMGRID_WORDS_PER_CELL;
            grid->pack_scratch[base + 0] = slot;
            grid->pack_scratch[base + 1] = fr | (fg << 8) | (fb << 16) | (br << 24);
            grid->pack_scratch[base + 2] = bgc | (bb << 8) | ((uint32_t)cell.attrs << 16);
            grid->pack_scratch[base + 3] = (uint32_t)cell.width | (cell_face << 8);
            /* Stage C (#699.5): the RETAINED combining marks, resolved to
             * atlas slots, composite over the base glyph in the shader. Read
             * straight from the store (module-internal) — the exposed cell
             * API stays base-only until its codegen extension. */
            for (uint32_t clear_word = 4; clear_word < YETTY_YSCENE_VTERMGRID_WORDS_PER_CELL;
                 ++clear_word) {
                grid->pack_scratch[base + clear_word] = 0;
            }
            if (cell_face == 0 && row < vtermgrid_active_store(grid)->rows &&
                col < vtermgrid_active_store(grid)->cols) {
                const struct yetty_yscene_vtermgrid_store_cell *stored =
                    &vtermgrid_active_store(grid)
                         ->cells[(size_t)row * vtermgrid_active_store(grid)->cols + col];
                uint32_t packed_marks = 0;
                for (uint8_t mark = 0; mark < stored->mark_count && packed_marks < 5; ++mark) {
                    struct uint32_result mark_idx =
                        grid->font->ops->get_glyph_index(grid->font, stored->marks[mark]);
                    if (YETTY_IS_OK(mark_idx)) {
                        grid->pack_scratch[base + 4 + packed_marks] = mark_idx.value;
                        ++packed_marks;
                    } else {
                        yetty_ycore_error_destroy(mark_idx.error);
                    }
                }
            }
        }
    }

    grid->has_blink_cells = saw_blink_cell;
    if (saw_blink_cell || (grid->cursor_blink && grid->cursor_visible)) {
        vtermgrid_blink_ensure_timer(grid);
    }

    wgpuQueueWriteBuffer(grid->queue, grid->cell_buffer, 0, grid->pack_scratch,
                         words * sizeof(uint32_t));
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result vtermgrid_gpu_ensure_bind_group(
    struct yetty_yscene_vtermgrid *grid)
{
    if (grid->bind_group_valid && grid->bind_group) {
        return YETTY_OK_VOID();
    }
    if (grid->bind_group) {
        wgpuBindGroupRelease(grid->bind_group);
        grid->bind_group = NULL;
    }
    if (!grid->cell_buffer || !grid->meta_buffer || !grid->atlas_view || !grid->sampler ||
        !grid->uniform_buffer) {
        return YETTY_ERR(yetty_ycore_void, "vtermgrid: bind group missing resource");
    }
    WGPUBindGroupEntry entries[7] = {0};
    entries[0].binding = 0;
    entries[0].buffer = grid->cell_buffer;
    entries[0].size = WGPU_WHOLE_SIZE;
    entries[1].binding = 1;
    entries[1].buffer = grid->meta_buffer;
    entries[1].size = WGPU_WHOLE_SIZE;
    entries[2].binding = 2;
    entries[2].textureView = grid->atlas_view;
    entries[3].binding = 3;
    entries[3].sampler = grid->sampler;
    entries[4].binding = 4;
    entries[4].buffer = grid->uniform_buffer;
    entries[4].size = sizeof(struct vtermgrid_uniforms);
    /* Fallback face bindings — the primary resources stand in when no
     * fallback font is attached (never sampled: face is always 0 then). */
    entries[5].binding = 5;
    entries[5].buffer = grid->fallback_meta_buffer ? grid->fallback_meta_buffer : grid->meta_buffer;
    entries[5].size = WGPU_WHOLE_SIZE;
    entries[6].binding = 6;
    entries[6].textureView =
        grid->fallback_atlas_view ? grid->fallback_atlas_view : grid->atlas_view;
    WGPUBindGroupDescriptor bg_desc = {0};
    bg_desc.layout = grid->bind_group_layout;
    bg_desc.entryCount = 7;
    bg_desc.entries = entries;
    grid->bind_group = wgpuDeviceCreateBindGroup(grid->device, &bg_desc);
    if (!grid->bind_group) {
        return YETTY_ERR(yetty_ycore_void, "vtermgrid: bind group create");
    }
    grid->bind_group_valid = 1;
    return YETTY_OK_VOID();
}

