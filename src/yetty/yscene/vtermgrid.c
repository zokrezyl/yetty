static uint32_t vtermgrid_pack_color(VTermColor color)
{
    return (uint32_t)color.red | ((uint32_t)color.green << 8) | ((uint32_t)color.blue << 16) |
           (0xFFu << 24);
}

static VTermColor vtermgrid_unpack_web_rgb(uint32_t rgb)
{
    VTermColor color;
    color.red = (uint8_t)(rgb & 0xFFu);
    color.green = (uint8_t)((rgb >> 8) & 0xFFu);
    color.blue = (uint8_t)((rgb >> 16) & 0xFFu);
    return color;
}

