/* Resolve libvterm's screen cell at (row,col) into the exposed packed form,
 * mapping the wide-continuation sentinel to width 0 and applying screen-wide
 * reverse. Out-of-range positions yield a blank default cell. */
static void vtermgrid_read_cell(struct yetty_yscene_vtermgrid *grid, uint32_t row, uint32_t col,
                                struct yetty_yscene_vtermgrid_cell *out)
{
    memset(out, 0, sizeof(*out));
    out->fg = grid->default_fg;
    out->bg = grid->default_bg;
    out->width = 1;
    if (row >= grid->rows || col >= grid->cols) {
        return;
    }
    /* #699.5: read from the cluster-preserving store. store_read resolves
     * reverse (cell attr XOR DECSCNM) into swapped colors — the same render
     * contract the fork's screen layer established; do NOT swap again. */
    vtermgrid_active_store(grid)->global_reverse = grid->reverse_video;
    struct yetty_yscene_vtermgrid_store_cell cell;
    yetty_yscene_vtermgrid_store_read(vtermgrid_active_store(grid), row, col, &cell);
    out->glyph = cell.codepoint; /* 0 = empty cell */
    out->width = cell.width;     /* 1 normal, 2 wide head, 0 wide continuation */
    out->fg = cell.fg;
    out->bg = cell.bg;
    out->attrs = cell.attrs;
}

