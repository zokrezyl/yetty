/*
 * engine.c — the independent ymux terminal engine: class@ymux:engine (#695
 * phase 1).
 *
 * One pane's canonical daemon-side terminal: a libvterm instance (the shared
 * library, used read-only through its public API), the primary and alternate
 * current-screen surfaces, cursor/pen/palette/mode state, terminal query
 * responses, and mode-aware input encoding. Emulator and parser state never
 * leave this object — attachments receive projected paint state, never
 * bytes. The engine speaks upward through a narrow plain-C host-callback
 * table (PTY output, clipboard, bell, title, history intake); it has no
 * GPU/renderer dependency and no relationship to yvterm.
 *
 * Row identity (#695 identity model, phase-1 subset): every surface row
 * carries a stable logical-line id minted from a monotonically increasing
 * counter (0 = invalid, never reused). Identity follows the row object
 * through structural moves (full-width scrolls rotate row objects); content
 * mutation never re-mints; rows destroyed by partial-region scrolls or
 * full clears are re-minted; a soft-wrap continuation row joins its head
 * row's logical line.
 *
 * The public header (include/yetty/api/ymux/engine.h) is generated by
 * codegen from the annotations here.
 */
