/*=============================================================================
 * yyjson read helpers (over the mutable master tree)
 *===========================================================================*/

static const char *mut_cstr(yyjson_mut_val *obj, const char *key)
{
    yyjson_mut_val *val = yyjson_mut_obj_get(obj, key);
    return (val && yyjson_mut_is_str(val)) ? yyjson_mut_get_str(val) : NULL;
}

static long mut_cint(yyjson_mut_val *obj, const char *key, long fallback)
{
    yyjson_mut_val *val = yyjson_mut_obj_get(obj, key);
    return (val && yyjson_mut_is_int(val)) ? (long)yyjson_mut_get_sint(val) : fallback;
}

static bool mut_cbool(yyjson_mut_val *obj, const char *key, bool fallback)
{
    yyjson_mut_val *val = yyjson_mut_obj_get(obj, key);
    return (val && yyjson_mut_is_bool(val)) ? yyjson_mut_get_bool(val) : fallback;
}

/* Join an nbformat text value (a string, or a list-of-strings concatenated with
 * no added separators) into an owned, NUL-terminated buffer. Returns NULL when
 * absent or not string-shaped. */
static char *join_mut_text(yyjson_mut_val *val)
{
    if (!val) {
        return NULL;
    }
    if (yyjson_mut_is_str(val)) {
        size_t len = yyjson_mut_get_len(val);
        char *buf = malloc(len + 1);
        if (!buf) {
            return NULL;
        }
        memcpy(buf, yyjson_mut_get_str(val), len);
        buf[len] = 0;
        return buf;
    }
    if (yyjson_mut_is_arr(val)) {
        size_t count = yyjson_mut_arr_size(val);
        size_t total = 0;
        for (size_t i = 0; i < count; i++) {
            yyjson_mut_val *item = yyjson_mut_arr_get(val, i);
            if (!item || !yyjson_mut_is_str(item)) {
                return NULL;
            }
            total += yyjson_mut_get_len(item);
        }
        char *buf = malloc(total + 1);
        if (!buf) {
            return NULL;
        }
        size_t offset = 0;
        for (size_t i = 0; i < count; i++) {
            yyjson_mut_val *item = yyjson_mut_arr_get(val, i);
            size_t len = yyjson_mut_get_len(item);
            memcpy(buf + offset, yyjson_mut_get_str(item), len);
            offset += len;
        }
        buf[total] = 0;
        return buf;
    }
    return NULL;
}

/* Join an array-of-strings with a newline between elements (an owned,
 * NUL-terminated buffer). Used for an error output's "traceback" frames, whose
 * elements are individual lines carrying no trailing newline. NULL when absent
 * or not an array-of-strings. */
static char *join_mut_lines(yyjson_mut_val *val)
{
    if (!val || !yyjson_mut_is_arr(val)) {
        return NULL;
    }
    size_t count = yyjson_mut_arr_size(val);
    size_t total = 0;
    for (size_t i = 0; i < count; i++) {
        yyjson_mut_val *item = yyjson_mut_arr_get(val, i);
        if (!item || !yyjson_mut_is_str(item)) {
            return NULL;
        }
        total += yyjson_mut_get_len(item) + 1; /* + newline */
    }
    char *buf = malloc(total + 1);
    if (!buf) {
        return NULL;
    }
    size_t offset = 0;
    for (size_t i = 0; i < count; i++) {
        yyjson_mut_val *item = yyjson_mut_arr_get(val, i);
        size_t len = yyjson_mut_get_len(item);
        memcpy(buf + offset, yyjson_mut_get_str(item), len);
        offset += len;
        buf[offset++] = '\n';
    }
    buf[offset] = 0;
    return buf;
}

/* Serialize one node to owned JSON text (NULL on absent/failure). */
static char *mut_val_to_text(yyjson_mut_val *val)
{
    return val ? yyjson_mut_val_write(val, 0, NULL) : NULL;
}

/*=============================================================================
 * Teardown
 *===========================================================================*/

static void output_free_fields(struct yetty_ynotebook_output *output)
{
    if (output->bundle) {
        yetty_ynotebook_mime_bundle_destroy(output->bundle);
        output->bundle = NULL;
    }
}

static void cell_free_fields(struct yetty_ynotebook_cell *cell)
{
    for (size_t i = 0; i < cell->output_count; i++) {
        struct yetty_yclass_object *output_obj = cell->outputs[i];
        if (!output_obj) {
            continue;
        }
        struct yetty_yclass_void_ptr_result output_r = output_from_obj(output_obj);
        if (YETTY_IS_OK(output_r)) {
            output_free_fields(output_r.value);
        }
        yetty_yclass_object_free(output_obj);
    }
    free(cell->outputs);
    cell->outputs = NULL;
    cell->output_count = 0;
}

static void notebook_clear(struct yetty_ynotebook_notebook *notebook)
{
    for (size_t i = 0; i < notebook->cell_count; i++) {
        struct yetty_yclass_object *cell_obj = notebook->cells[i];
        if (!cell_obj) {
            continue;
        }
        struct yetty_yclass_void_ptr_result cell_r = cell_from_obj(cell_obj);
        if (YETTY_IS_OK(cell_r)) {
            cell_free_fields(cell_r.value);
        }
        yetty_yclass_object_free(cell_obj);
    }
    free(notebook->cells);
    notebook->cells = NULL;
    notebook->cell_count = 0;
    if (notebook->doc) {
        yyjson_mut_doc_free(notebook->doc);
        notebook->doc = NULL;
    }
    notebook->root = NULL;
}

/*=============================================================================
 * Parse: build view-objects over the master tree
 *===========================================================================*/

/* For a display_data / execute_result output, build a mime_bundle object from
 * the output's `data` (+ `metadata`) sub-objects. */
static struct yetty_ycore_void_result output_build_bundle(struct yetty_ynotebook_output *output)
{
    const char *type = mut_cstr(output->node, "output_type");
    if (!type) {
        return YETTY_OK_VOID();
    }
    if (strcmp(type, "display_data") != 0 && strcmp(type, "execute_result") != 0) {
        return YETTY_OK_VOID();
    }

    char *data_text = mut_val_to_text(yyjson_mut_obj_get(output->node, "data"));
    char *metadata_text = mut_val_to_text(yyjson_mut_obj_get(output->node, "metadata"));

    struct yetty_yclass_ctx ctx = {0};
    struct yetty_yclass_object_ptr_result bundle_r = yetty_ynotebook_mime_bundle_create(&ctx);
    if (YETTY_IS_ERR(bundle_r)) {
        free(data_text);
        free(metadata_text);
        return YETTY_ERR(yetty_ycore_void, "output build_bundle: create failed", bundle_r);
    }
    output->bundle = bundle_r.value;

    struct yetty_ycore_void_result load_r = yetty_ynotebook_mime_bundle_from_json_text(
        output->bundle, data_text ? data_text : "{}", metadata_text);
    free(data_text);
    free(metadata_text);
    YETTY_RETURN_IF_ERR(yetty_ycore_void, load_r, "output build_bundle: bundle load");
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result cell_build_outputs(struct yetty_ynotebook_cell *cell)
{
    yyjson_mut_val *outputs = yyjson_mut_obj_get(cell->node, "outputs");
    if (!outputs || !yyjson_mut_is_arr(outputs)) {
        return YETTY_OK_VOID();
    }

    size_t count = yyjson_mut_arr_size(outputs);
    if (count == 0) {
        return YETTY_OK_VOID();
    }

    cell->outputs = calloc(count, sizeof(*cell->outputs));
    if (!cell->outputs) {
        return YETTY_ERR(yetty_ycore_void, "cell build_outputs: vector alloc failed");
    }

    for (size_t i = 0; i < count; i++) {
        yyjson_mut_val *output_node = yyjson_mut_arr_get(outputs, i);
        struct yetty_yclass_ctx ctx = {0};
        struct yetty_yclass_object_ptr_result output_r = yetty_ynotebook_output_create(&ctx);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, output_r, "cell build_outputs: output create");
        struct yetty_yclass_object *output_obj = output_r.value;

        struct yetty_yclass_void_ptr_result data_r = output_from_obj(output_obj);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, data_r, "cell build_outputs: output from_obj");
        struct yetty_ynotebook_output *output = data_r.value;
        output->doc = cell->doc;
        output->node = output_node;

        struct yetty_ycore_void_result bundle_r = output_build_bundle(output);
        if (YETTY_IS_ERR(bundle_r)) {
            yetty_yclass_object_free(output_obj);
            return YETTY_ERR(yetty_ycore_void, "cell build_outputs: build bundle", bundle_r);
        }

        cell->outputs[cell->output_count++] = output_obj;
    }
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result notebook_populate(struct yetty_ynotebook_notebook *notebook,
                                                        const char *json, size_t len)
{
    yyjson_doc *input = yyjson_read(json, len, 0);
    if (!input) {
        return YETTY_ERR(yetty_ycore_void, "notebook load: JSON parse failed");
    }
    yyjson_mut_doc *master = yyjson_doc_mut_copy(input, NULL);
    yyjson_doc_free(input);
    if (!master) {
        return YETTY_ERR(yetty_ycore_void, "notebook load: mutable copy failed");
    }

    yyjson_mut_val *root = yyjson_mut_doc_get_root(master);
    if (!root || !yyjson_mut_is_obj(root)) {
        yyjson_mut_doc_free(master);
        return YETTY_ERR(yetty_ycore_void, "notebook load: root is not a JSON object");
    }

    notebook_clear(notebook);
    notebook->doc = master;
    notebook->root = root;

    yyjson_mut_val *cells = yyjson_mut_obj_get(root, "cells");
    if (!cells || !yyjson_mut_is_arr(cells)) {
        return YETTY_OK_VOID(); /* a notebook with no cells is valid */
    }

    size_t count = yyjson_mut_arr_size(cells);
    if (count == 0) {
        return YETTY_OK_VOID();
    }

    notebook->cells = calloc(count, sizeof(*notebook->cells));
    if (!notebook->cells) {
        return YETTY_ERR(yetty_ycore_void, "notebook load: cell vector alloc failed");
    }

    for (size_t i = 0; i < count; i++) {
        yyjson_mut_val *cell_node = yyjson_mut_arr_get(cells, i);
        struct yetty_yclass_ctx ctx = {0};
        struct yetty_yclass_object_ptr_result cell_r = yetty_ynotebook_cell_create(&ctx);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, cell_r, "notebook load: cell create");
        struct yetty_yclass_object *cell_obj = cell_r.value;

        struct yetty_yclass_void_ptr_result data_r = cell_from_obj(cell_obj);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, data_r, "notebook load: cell from_obj");
        struct yetty_ynotebook_cell *cell = data_r.value;
        cell->doc = master;
        cell->node = cell_node;

        struct yetty_ycore_void_result outputs_r = cell_build_outputs(cell);
        if (YETTY_IS_ERR(outputs_r)) {
            cell_free_fields(cell);
            yetty_yclass_object_free(cell_obj);
            return YETTY_ERR(yetty_ycore_void, "notebook load: build outputs", outputs_r);
        }

        notebook->cells[notebook->cell_count++] = cell_obj;
    }
    return YETTY_OK_VOID();
}

