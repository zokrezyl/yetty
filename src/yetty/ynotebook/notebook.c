/*
 * ynotebook document model — the nbformat 4 notebook, its cells, and their
 * outputs, as yclass classes.
 *
 *   ynotebook:notebook  — the document. Owns a master mutable JSON tree (the
 *                         whole .ipynb) plus a vector of cell view-objects.
 *   ynotebook:cell      — one cell: a typed view over its node in the master
 *                         tree, plus a vector of output view-objects.
 *   ynotebook:output    — one output: a typed view over its node, plus a
 *                         `mime_bundle` object for display_data / execute_result.
 *
 * Fidelity: the cells and outputs are *views* over the retained master tree, so
 * serializing the notebook re-emits that tree — unknown fields, metadata, and
 * representations Yetty does not model all survive a load/save cycle. Edits go
 * through methods that mutate the same tree.
 *
 * The public interface is generated by yclass codegen from the annotations
 * below — never hand-write notebook.h. JSON is parsed/written with yyjson;
 * that dependency stays out of the public method surface (load/serialize take
 * and return JSON text).
 */

