/*===========================================================================
 * Grid model lifecycle — the model lives embedded in the vterm object.
 *=========================================================================*/

static void screen_free_lines(struct yetty_yvterm_grid *grid, struct yetty_yvterm_screen *screen)
{
    if (!screen->lines) {
        return;
    }
    for (uint32_t line = 0; line < screen->line_count; ++line) {
        struct yetty_yvterm_line *current = &screen->lines[line];
        release_line_rich(current);
        yetty_ycore_memtag_free(&grid->ring_memtag, current->text_cells);
    }
    free(screen->lines);
    screen->lines = NULL;
    screen->line_count = 0;
}

static struct yetty_ycore_void_result screen_alloc_lines(struct yetty_yvterm_grid *grid,
                                                         struct yetty_yvterm_screen *screen,
                                                         uint32_t line_count, uint32_t cols)
{
    screen->lines = calloc(line_count, sizeof(struct yetty_yvterm_line));
    if (!screen->lines) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: line array allocation failed");
    }
    screen->line_count = line_count;
    for (uint32_t line = 0; line < line_count; ++line) {
        screen->lines[line].text_cells = yetty_ycore_memtag_calloc(
            &grid->ring_memtag, cols, sizeof(struct yetty_yvterm_text_cell));
        if (!screen->lines[line].text_cells) {
            screen_free_lines(grid, screen);
            return YETTY_ERR(yetty_ycore_void, "yvterm: line allocation failed");
        }
    }
    return YETTY_OK_VOID();
}

/* Blank every line of a ring at the given width with the terminal default
 * colours. Explicit cols/fg/bg because resize builds rings at the new width
 * before the grid's own fields are committed. */
static void screen_blank_all(struct yetty_yvterm_screen *screen, uint32_t cols, uint32_t fg,
                             uint32_t bg)
{
    for (uint32_t slot = 0; slot < screen->line_count; ++slot) {
        fill_line_blank(&screen->lines[slot], cols, fg, bg);
    }
}

/* Size the blank fallback line to the current width. */
static struct yetty_ycore_void_result grid_blank_line_resize(struct yetty_yvterm_grid *grid,
                                                             uint32_t cols)
{
    struct yetty_yvterm_text_cell *cells = yetty_ycore_memtag_calloc(
        &grid->ring_memtag, cols ? cols : 1u, sizeof(struct yetty_yvterm_text_cell));
    if (!cells) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: blank line alloc failed");
    }
    yetty_ycore_memtag_free(&grid->ring_memtag, grid->blank_line.text_cells);
    memset(&grid->blank_line, 0, sizeof(grid->blank_line));
    grid->blank_line.text_cells = cells;
    for (uint32_t col = 0; col < cols; ++col) {
        blank_cell(&cells[col], grid->default_fg, grid->default_bg);
    }
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result grid_model_init(struct yetty_yvterm_grid *grid, uint32_t cols,
                                                      uint32_t rows, uint32_t scrollback_rows,
                                                      uint32_t hot_rows)
{
    grid->cols = cols;
    grid->visible_rows = rows;
    /* scrollback_rows is the TOTAL retention cap across all tiers; 0 means
     * unlimited (the cold tier absorbs the depth). hot_rows falls back to the
     * built-in default when the caller passes 0 (no config). */
    grid->scrollback_rows = scrollback_rows;
    grid->hot_rows = hot_rows ? hot_rows : YVTERM_HOT_ROWS_DEFAULT;
    grid->ring_history_cap = (grid->scrollback_rows && grid->scrollback_rows < grid->hot_rows)
                                 ? grid->scrollback_rows
                                 : grid->hot_rows;
    yetty_yvterm_tiers_init(&grid->tiers);
    grid->tiers.warm_bytes_budget = YVTERM_WARM_BYTES_DEFAULT;
    grid->tiers.total_line_cap = grid->scrollback_rows;
    grid->ring_memtag.name = "yvterm/ring";
    grid->archive_memtag.name = "yvterm/archive";
    grid->tiers.memtag = &grid->archive_memtag;

    /* Primary ring: visible lines plus a small initial history capacity; the
     * ring grows exponentially toward visible + the hot window as scrollback
     * actually fills (screen_grow_ring, driven from roll_up). Alternate ring:
     * visible lines only — no scrollback. */
    uint32_t initial_history = grid->ring_history_cap < YVTERM_SCROLLBACK_INITIAL_ROWS
                                   ? grid->ring_history_cap
                                   : YVTERM_SCROLLBACK_INITIAL_ROWS;
    struct yetty_ycore_void_result primary_res =
        screen_alloc_lines(grid, &grid->primary, rows + initial_history, cols);
    YETTY_RETURN_IF_ERR(yetty_ycore_void, primary_res, "yvterm: grid_model_init primary ring");
    struct yetty_ycore_void_result alternate_res =
        screen_alloc_lines(grid, &grid->alternate, rows, cols);
    if (YETTY_IS_ERR(alternate_res)) {
        screen_free_lines(grid, &grid->primary);
        return YETTY_ERR(yetty_ycore_void, "yvterm: grid_model_init alternate ring", alternate_res);
    }

    grid->vterm = vterm_new((int)rows, (int)cols);
    if (!grid->vterm) {
        screen_free_lines(grid, &grid->primary);
        screen_free_lines(grid, &grid->alternate);
        return YETTY_ERR(yetty_ycore_void, "yvterm: vterm_new failed");
    }
    vterm_set_utf8(grid->vterm, 1);
    grid->state = vterm_obtain_state(grid->vterm);
    vterm_state_set_callbacks(grid->state, grid_state_callbacks(), grid);

    VTermColor default_fg;
    VTermColor default_bg;
    vterm_state_get_default_colors(grid->state, &default_fg, &default_bg);
    grid->default_fg = pack_color(default_fg);
    grid->default_bg = pack_color(default_bg);

    vterm_state_reset(grid->state, 1);
    grid->pen_fg = grid->default_fg;
    grid->pen_bg = grid->default_bg;
    grid->cursor_visible = 1u;

    struct yetty_ycore_void_result blank_res = grid_blank_line_resize(grid, cols);
    if (YETTY_IS_ERR(blank_res)) {
        vterm_free(grid->vterm);
        grid->vterm = NULL;
        grid->state = NULL;
        screen_free_lines(grid, &grid->primary);
        screen_free_lines(grid, &grid->alternate);
        return YETTY_ERR(yetty_ycore_void, "yvterm: grid_model_init blank line", blank_res);
    }

    screen_blank_all(&grid->primary, cols, grid->default_fg, grid->default_bg);
    screen_blank_all(&grid->alternate, cols, grid->default_fg, grid->default_bg);
    mark_dirty_all(grid);
    return YETTY_OK_VOID();
}

static void grid_model_teardown(struct yetty_yvterm_grid *grid)
{
    if (grid->memtag_registry) {
        yetty_ycore_memtag_registry_remove(grid->memtag_registry, &grid->ring_memtag);
        yetty_ycore_memtag_registry_remove(grid->memtag_registry, &grid->archive_memtag);
        grid->memtag_registry = NULL;
    }
    if (grid->vterm) {
        vterm_free(grid->vterm);
        grid->vterm = NULL;
        grid->state = NULL;
    }
    screen_free_lines(grid, &grid->primary);
    screen_free_lines(grid, &grid->alternate);
    yetty_yvterm_tiers_destroy(&grid->tiers);
    yetty_ycore_memtag_free(&grid->ring_memtag, grid->blank_line.text_cells);
    memset(&grid->blank_line, 0, sizeof(grid->blank_line));
    free(grid->window_lines);
    grid->window_lines = NULL;
    free(grid->window_slots);
    grid->window_slots = NULL;
    grid->window_capacity = 0;
    grid->window_count = 0;
}

/*===========================================================================
 * Resize with reflow — re-wrap the soft-wrapped text to the new width.
 *
 * Models libvterm's screen-layer resize (src/libvterm-0.3.3/src/screen.c
 * resize_buffer): physical lines are grouped into logical lines along the
 * `continuation` flag, each logical line is re-wrapped at the new width, and
 * the result is laid back into the ring with the bottom of the content pinned
 * to the bottom of the visible screen (so the cursor and newest output stay in
 * view, and a taller window reveals scrollback above). The cursor is tracked
 * through the reflow by its absolute offset within its logical line.
 *
 * Scope note: only text cells reflow. Anchored rich content (primitives /
 * composites) is released on resize, as it was before reflow existed — its
 * placement is row-relative and re-wrapping invalidates it. Preserving rich
 * content across reflow is a separate follow-up.
 *=========================================================================*/

/* Number of leading columns of a line that hold real content — the column after
 * the last cell with a non-zero codepoint. Never-written / erased cells carry
 * codepoint 0 and are trimmed; explicit spaces (codepoint 0x20) are kept. */
static uint32_t line_used_cols(const struct yetty_yvterm_line *line, uint32_t cols)
{
    uint32_t used = 0;
    for (uint32_t col = 0; col < cols; ++col) {
        if (line->text_cells[col].codepoint != 0) {
            used = col + 1u;
        }
    }
    return used;
}

/* One physical source row feeding the reflow, paired with whether it continues
 * the row above it within the gathered window. */
struct yetty_yvterm_reflow_source {
    struct yetty_yvterm_line *line;
    int continuation;
};

/* One logical line (a maximal run of continuation-joined source rows) and how it
 * maps onto the new width. */
struct yetty_yvterm_reflow_logical {
    uint32_t first;       /* index of the first source row */
    uint32_t seg_count;   /* number of source rows joined into this logical line */
    uint32_t content_len; /* total content cells across the joined rows */
    uint32_t new_height;  /* physical rows this occupies at the new width */
    uint32_t start_gidx;  /* global new-row index where this logical line begins */
};

/* Map a global new-row index to its ring slot in a freshly laid-out (base 0)
 * ring: the bottom `new_rows` rows are visible at slots [0, new_rows); rows above
 * them are scrollback at slot (new_line_count - back). Returns 0 (and leaves
 * *out_slot untouched) for a row evicted past the retained scrollback. */
static int reflow_gidx_to_slot(uint32_t gidx, uint32_t visible_top, uint32_t new_rows,
                               uint32_t new_line_count, uint32_t *out_slot)
{
    if (gidx >= visible_top && gidx < visible_top + new_rows) {
        *out_slot = gidx - visible_top;
        return 1;
    }
    if (gidx < visible_top) {
        uint32_t back = visible_top - gidx;
        /* The ring spans new_line_count = new_rows + scrollback, so anything
         * deeper than (new_line_count - new_rows) history rows has aged out. */
        if (back > new_line_count - new_rows) {
            return 0;
        }
        *out_slot = new_line_count - back;
        return 1;
    }
    return 0;
}

/* Steal a source line's whole rich backing (arena + primitive descriptors +
 * composite array) onto an empty destination line — pointers move, the source
 * is left empty so the old-ring teardown frees nothing for it. */
static void take_line_rich(struct yetty_yvterm_line *dst, struct yetty_yvterm_line *src)
{
    dst->composites = src->composites;
    dst->composite_count = src->composite_count;
    dst->composite_capacity = src->composite_capacity;
    dst->primitives = src->primitives;
    dst->primitive_count = src->primitive_count;
    dst->primitive_capacity = src->primitive_capacity;
    dst->arena = src->arena;
    dst->arena_count = src->arena_count;
    dst->arena_capacity = src->arena_capacity;
    dst->rich_span_rows = src->rich_span_rows;
    dst->envelope_count = src->envelope_count;
    dst->view_stamp = src->view_stamp;

    src->composites = NULL;
    src->composite_count = 0;
    src->composite_capacity = 0;
    src->primitives = NULL;
    src->primitive_count = 0;
    src->primitive_capacity = 0;
    src->arena = NULL;
    src->arena_count = 0;
    src->arena_capacity = 0;
    src->rich_span_rows = 0;
    src->envelope_count = 0;
    src->view_stamp = 0;
}

/* Move a source line's anchored rich content (SDF primitive arena + descriptors
 * and owned composites) onto a destination line in the new ring, so figures and
 * SDF drawables survive a resize instead of being dropped. The fast path steals
 * the whole backing when the destination is still empty; when two source rows
 * fold onto the same new row (e.g. widening packs a wrapped logical line), the
 * source's content is APPENDED so nothing is lost — the primitive arena is
 * concatenated (descriptor offsets rebased), the descriptor and composite arrays
 * grown. Each category transfers all-or-nothing: anything that can't grow is left
 * on the source for the old-ring teardown, never leaked or double-owned. */
static struct yetty_ycore_void_result merge_line_rich(struct yetty_yvterm_line *dst,
                                                      struct yetty_yvterm_line *src)
{
    if (!src->composite_count && !src->primitive_count && !src->arena_count) {
        return YETTY_OK_VOID();
    }
    if (!dst->composites && !dst->primitives && !dst->arena) {
        take_line_rich(dst, src);
        dst->dirty = 1;
        return YETTY_OK_VOID();
    }

    /* Primitives reference the arena by offset, so move them together: grow both
     * first, then commit, rebasing each descriptor's offset by where the source
     * arena lands inside the destination arena. */
    if (src->primitive_count || src->arena_count) {
        struct yetty_ycore_void_result arena_res =
            ensure_arena(dst, dst->arena_count + src->arena_count);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, arena_res, "yvterm merge_line_rich: grow arena");
        struct yetty_ycore_void_result prim_res =
            ensure_primitives(dst, dst->primitive_count + src->primitive_count);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, prim_res, "yvterm merge_line_rich: grow primitives");
        uint32_t arena_base = dst->arena_count;
        if (src->arena_count) {
            memcpy(dst->arena + dst->arena_count, src->arena,
                   (size_t)src->arena_count * sizeof(uint32_t));
            dst->arena_count += src->arena_count;
        }
        for (uint32_t i = 0; i < src->primitive_count; ++i) {
            dst->primitives[dst->primitive_count] = src->primitives[i];
            dst->primitives[dst->primitive_count].arena_offset += arena_base;
            dst->primitive_count++;
        }
        dst->envelope_count += src->envelope_count;
        free(src->primitives);
        free(src->arena);
        src->primitives = NULL;
        src->primitive_count = 0;
        src->primitive_capacity = 0;
        src->arena = NULL;
        src->arena_count = 0;
        src->arena_capacity = 0;
        src->envelope_count = 0;
    }

    if (src->composite_count) {
        struct yetty_ycore_void_result comp_res =
            ensure_composites(dst, dst->composite_count + src->composite_count);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, comp_res, "yvterm merge_line_rich: grow composites");
        for (uint32_t i = 0; i < src->composite_count; ++i) {
            dst->composites[dst->composite_count++] = src->composites[i];
        }
        free(src->composites);
        src->composites = NULL;
        src->composite_count = 0;
        src->composite_capacity = 0;
    }

    /* Two blocks folded onto one row: keep the taller span so the merged
     * content still leaves the scrollback by its lowest overlapping line. */
    if (src->rich_span_rows > dst->rich_span_rows) {
        dst->rich_span_rows = src->rich_span_rows;
    }
    src->rich_span_rows = 0;
    if (src->view_stamp > dst->view_stamp) {
        dst->view_stamp = src->view_stamp;
    }
    src->view_stamp = 0;

    dst->dirty = 1;
    return YETTY_OK_VOID();
}

/* Rectangle-copy resize of the alternate ring: full-screen apps own their
 * redraw and have neither scrollback nor soft-wrap, so there is nothing to
 * reflow. Preserve the overlapping top-left rectangle to avoid a blank flash;
 * the app repaints the rest on the SIGWINCH it gets from the PTY resize. The
 * ring stays visible-only (new_rows lines); scroll state resets. Rich content
 * on the old ring goes down with it — an alternate surface is repainted
 * wholesale anyway. Does NOT commit grid-global dims/cursor — the caller
 * (grid_model_resize) does, once BOTH rings are resized. */
static struct yetty_ycore_void_result screen_resize_rect(struct yetty_yvterm_grid *grid,
                                                         struct yetty_yvterm_screen *screen,
                                                         uint32_t new_cols, uint32_t new_rows,
                                                         struct yetty_yvterm_screen *out_new)
{
    uint32_t old_cols = grid->cols;
    uint32_t old_rows = grid->visible_rows;

    struct yetty_yvterm_screen tmp = {0};
    struct yetty_ycore_void_result lines_res = screen_alloc_lines(grid, &tmp, new_rows, new_cols);
    YETTY_RETURN_IF_ERR(yetty_ycore_void, lines_res, "yvterm: screen_resize_rect alloc_lines");
    screen_blank_all(&tmp, new_cols, grid->default_fg, grid->default_bg);

    uint32_t copy_rows = old_rows < new_rows ? old_rows : new_rows;
    uint32_t copy_cols = old_cols < new_cols ? old_cols : new_cols;
    for (uint32_t row = 0; row < copy_rows; ++row) {
        struct yetty_yvterm_text_cell *dst = tmp.lines[row].text_cells;
        const struct yetty_yvterm_text_cell *src = screen_line_at(screen, row)->text_cells;
        for (uint32_t col = 0; col < copy_cols; ++col) {
            dst[col] = src[col];
        }
        tmp.lines[row].dirty = 1;
    }

    /* Emit only — the caller commits both rings + dimensions together, so a
     * failure of the OTHER ring's resize leaves everything untouched. */
    *out_new = tmp;
    return YETTY_OK_VOID();
}

/* Reflow-resize a screen's ring (in practice: the primary — the alternate is
 * rectangle-copied). inout_cursor_row/inout_cursor_col carry the screen's
 * cursor through the re-wrap by its absolute offset within its logical line;
 * pass NULL for both when reflowing the DORMANT primary during an alt-screen
 * session — its cursor lives in libvterm's saved state (restored and clamped
 * on ?1049l), so there is nothing to track and nothing is written back. Does
 * NOT commit grid-global dims/cursor and does NOT resize libvterm — the caller
 * (grid_model_resize) does, once BOTH rings are resized. */
static struct yetty_ycore_void_result screen_resize_reflow(struct yetty_yvterm_grid *grid,
                                                           struct yetty_yvterm_screen *screen,
                                                           uint32_t new_cols, uint32_t new_rows,
                                                           uint32_t *inout_cursor_row,
                                                           uint32_t *inout_cursor_col,
                                                           struct yetty_yvterm_screen *out_new)
{
    uint32_t old_cols = grid->cols;
    uint32_t old_rows = grid->visible_rows;
    int have_cursor = inout_cursor_row && inout_cursor_col;
    uint32_t scrollback_cap = screen->line_count - old_rows;
    uint32_t hist =
        screen->total_scrolled < scrollback_cap ? screen->total_scrolled : scrollback_cap;

    /* Trim trailing blank rows below the content/cursor so the reflow does not
     * manufacture empty scrollback, but never trim history or the cursor line. */
    int content_bottom = -1;
    for (uint32_t row = 0; row < old_rows; ++row) {
        if (line_used_cols(screen_line_at(screen, row), old_cols) > 0) {
            content_bottom = (int)row;
        }
    }
    int last_kept = content_bottom;
    if (have_cursor && (int)*inout_cursor_row > last_kept) {
        last_kept = (int)*inout_cursor_row;
    }
    uint32_t visible_kept = last_kept >= 0 ? (uint32_t)last_kept + 1u : 0u;
    uint32_t src_count = hist + visible_kept;

    struct yetty_yvterm_reflow_source *src = calloc(src_count ? src_count : 1u, sizeof(*src));
    struct yetty_yvterm_reflow_logical *logical =
        calloc(src_count ? src_count : 1u, sizeof(*logical));
    if (!src || !logical) {
        free(src);
        free(logical);
        return YETTY_ERR(yetty_ycore_void, "yvterm: screen_resize_reflow scratch alloc failed");
    }
    for (uint32_t i = 0; i < src_count; ++i) {
        struct yetty_yvterm_line *line = screen_line_at_signed(screen, (int)i - (int)hist);
        src[i].line = line;
        /* The oldest gathered row starts a fresh logical line even if its flag is
         * set — whatever it continued from has already been evicted. */
        src[i].continuation = (i > 0) && line->continuation;
    }
    uint32_t cursor_src = have_cursor ? hist + *inout_cursor_row : 0u;

    /* Pass 1: group into logical lines, size each at the new width, and locate
     * the cursor by its absolute cell offset within its logical line. */
    uint32_t logical_count = 0;
    uint32_t total_new = 0;
    uint32_t cursor_gidx = 0;
    uint32_t cursor_new_col = 0;
    int cursor_found = 0;
    for (uint32_t i = 0; i < src_count;) {
        uint32_t first = i;
        i++;
        while (i < src_count && src[i].continuation) {
            i++;
        }
        uint32_t seg_count = i - first;
        uint32_t content_len =
            (seg_count - 1u) * old_cols + line_used_cols(src[i - 1u].line, old_cols);
        uint32_t new_height = content_len ? (content_len + new_cols - 1u) / new_cols : 1u;

        struct yetty_yvterm_reflow_logical *entry = &logical[logical_count];
        entry->first = first;
        entry->seg_count = seg_count;
        entry->content_len = content_len;
        entry->new_height = new_height;
        entry->start_gidx = total_new;

        if (have_cursor && !cursor_found && cursor_src >= first && cursor_src < i) {
            uint32_t offset = (cursor_src - first) * old_cols + *inout_cursor_col;
            if (offset > content_len) {
                offset = content_len;
            }
            uint32_t crow = new_cols ? offset / new_cols : 0u;
            uint32_t ccol = new_cols ? offset % new_cols : 0u;
            if (crow >= new_height) {
                crow = new_height - 1u;
                ccol = new_cols ? new_cols - 1u : 0u;
            }
            cursor_gidx = total_new + crow;
            cursor_new_col = ccol;
            cursor_found = 1;
        }

        total_new += new_height;
        logical_count++;
    }
    if (!cursor_found) {
        cursor_gidx = total_new ? total_new - 1u : 0u;
        cursor_new_col = 0;
    }

    /* Bottom-align the content: the last new row sits on the last visible row, so
     * everything above it (older output and history) becomes scrollback. Size
     * the new ring to the content actually retained, not the configured
     * maximum — the ring re-grows lazily on the next roll (screen_grow_ring). */
    uint32_t visible_top = total_new > new_rows ? total_new - new_rows : 0u;
    uint32_t kept_history =
        visible_top < grid->ring_history_cap ? visible_top : grid->ring_history_cap;
    uint32_t new_line_count = new_rows + kept_history;

    struct yetty_yvterm_screen tmp = {0};
    struct yetty_ycore_void_result lines_res =
        screen_alloc_lines(grid, &tmp, new_line_count, new_cols);
    if (YETTY_IS_ERR(lines_res)) {
        free(src);
        free(logical);
        return YETTY_ERR(yetty_ycore_void, "yvterm: screen_resize_reflow alloc_lines", lines_res);
    }
    screen_blank_all(&tmp, new_cols, grid->default_fg, grid->default_bg);

    /* Pass 2: emit each logical line's wrapped rows into the new ring. With base
     * 0, visible row v lives at slot v and scrollback row -k at slot
     * (line_count - k); rows older than the retained window are dropped. */
    for (uint32_t li = 0; li < logical_count; ++li) {
        struct yetty_yvterm_reflow_logical *entry = &logical[li];
        uint32_t first = entry->first;
        for (uint32_t rr = 0; rr < entry->new_height; ++rr) {
            uint32_t gidx = entry->start_gidx + rr;
            uint32_t slot;
            if (!reflow_gidx_to_slot(gidx, visible_top, new_rows, new_line_count, &slot)) {
                continue;
            }

            struct yetty_yvterm_line *dst = &tmp.lines[slot];
            for (uint32_t col = 0; col < new_cols; ++col) {
                uint32_t pos = rr * new_cols + col;
                if (pos < entry->content_len) {
                    uint32_t seg = first + pos / old_cols;
                    uint32_t scol = pos % old_cols;
                    dst->text_cells[col] = src[seg].line->text_cells[scol];
                } else {
                    blank_cell(&dst->text_cells[col], grid->default_fg, grid->default_bg);
                }
            }
            dst->continuation = rr > 0 ? 1 : 0;
            dst->dirty = 1;
        }

        /* Carry anchored rich content over: a figure / SDF drawable lives on one
         * source row and must follow its text to the new ring. It re-homes onto
         * the new row holding that source segment's first cell (its top), so it
         * stays anchored where the reflowed text put it. */
        for (uint32_t seg = 0; seg < entry->seg_count; ++seg) {
            struct yetty_yvterm_line *src_line = src[first + seg].line;
            if (!src_line->composite_count && !src_line->primitive_count) {
                continue;
            }
            uint32_t seg_offset = seg * old_cols;
            uint32_t seg_row = new_cols ? seg_offset / new_cols : 0u;
            if (seg_row >= entry->new_height) {
                seg_row = entry->new_height - 1u;
            }
            uint32_t slot;
            if (!reflow_gidx_to_slot(entry->start_gidx + seg_row, visible_top, new_rows,
                                     new_line_count, &slot)) {
                continue;
            }
            struct yetty_ycore_void_result merge_res = merge_line_rich(&tmp.lines[slot], src_line);
            if (YETTY_IS_ERR(merge_res)) {
                screen_free_lines(grid, &tmp);
                free(src);
                free(logical);
                return YETTY_ERR(yetty_ycore_void, "yvterm: screen_resize_reflow merge rich",
                                 merge_res);
            }
        }
    }

    /* Emit only — the caller commits both rings + dimensions together. */
    tmp.base = 0;
    tmp.total_scrolled = visible_top;
    *out_new = tmp;

    if (have_cursor) {
        uint32_t reflowed_row = cursor_gidx >= visible_top ? cursor_gidx - visible_top : 0u;
        if (reflowed_row >= new_rows) {
            reflowed_row = new_rows - 1u;
        }
        *inout_cursor_row = reflowed_row;
        *inout_cursor_col =
            cursor_new_col < new_cols ? cursor_new_col : (new_cols ? new_cols - 1u : 0u);
    }

    free(src);
    free(logical);
    return YETTY_OK_VOID();
}

/* Lazy history reflow: drain the primary ring's retained history into the
 * archive (at the pre-resize width) so the reflow below only re-wraps the
 * visible screen. Resize cost becomes O(visible + hot) regardless of history
 * depth, and the archive is never rewritten on geometry changes — archived
 * lines keep their stored layout (continuation flags + original width are in
 * the serial format for a future view-time re-wrap). Only meaningful when the
 * archive is enabled; otherwise the ring reflows wholesale as before. */
static void grid_drain_history_to_archive(struct yetty_yvterm_grid *grid)
{
    if (!grid_archive_enabled(grid)) {
        return;
    }
    struct yetty_yvterm_screen *screen = &grid->primary;
    uint32_t history_rows = screen_history_rows(grid, screen);
    for (uint32_t index = 0; index < history_rows; ++index) {
        struct yetty_yvterm_line *line =
            screen_line_at_signed(screen, (int)index - (int)history_rows);
        grid_archive_recycled_line(grid, line);
        /* Leave the line's text in place (the reflow gather below no longer
         * touches history rows); drop its rich backing so the old ring's
         * teardown cannot double-own what the archive now carries. */
        release_line_rich(line);
    }
    if (history_rows) {
        /* The ring's history is archived: rebase the scroll origin so the
         * reflow gathers the visible screen only (it re-bases the origin
         * itself afterwards, as it always has). */
        screen->total_scrolled = 0;
        ydebug("scroll tiers: resize drained %u history line(s) to the archive", history_rows);
    }
}

static struct yetty_ycore_void_result grid_model_resize(struct yetty_yvterm_grid *grid,
                                                        uint32_t cols, uint32_t rows)
{
    if (cols == grid->cols && rows == grid->visible_rows) {
        return YETTY_OK_VOID();
    }

    grid_drain_history_to_archive(grid);

    /* TRANSACTIONAL resize: build BOTH replacement rings first (against the
     * old geometry, reading the old rings), and only when both succeeded
     * commit rings + dimensions + cursor together. A failure of either
     * build frees the finished half and leaves rings and geometry exactly
     * as they were — switching screens can never apply old column bounds
     * to a smaller allocation. (The history drain above is not rolled
     * back: the archived rows stay reachable through the archive and the
     * ring's origin was rebased, so the grid remains self-consistent.) */
    uint32_t reflow_cursor_row = grid->cursor_row;
    uint32_t reflow_cursor_col = grid->cursor_col;
    struct yetty_yvterm_screen new_primary = {0};
    struct yetty_yvterm_screen new_alternate = {0};
    struct yetty_ycore_void_result primary_res;
    if (grid->alt_screen) {
        /* The live cursor belongs to the alternate screen; the dormant primary
         * reflows cursor-less (its cursor is libvterm's saved one, restored
         * and clamped on ?1049l). Rectangle semantics for the live alternate
         * cursor: clamp. */
        primary_res =
            screen_resize_reflow(grid, &grid->primary, cols, rows, NULL, NULL, &new_primary);
        if (reflow_cursor_row >= rows) {
            reflow_cursor_row = rows - 1u;
        }
        if (reflow_cursor_col >= cols) {
            reflow_cursor_col = cols - 1u;
        }
    } else {
        primary_res = screen_resize_reflow(grid, &grid->primary, cols, rows, &reflow_cursor_row,
                                           &reflow_cursor_col, &new_primary);
    }
    YETTY_RETURN_IF_ERR(yetty_ycore_void, primary_res, "yvterm: resize primary reflow");
    struct yetty_ycore_void_result alternate_res =
        screen_resize_rect(grid, &grid->alternate, cols, rows, &new_alternate);
    if (YETTY_IS_ERR(alternate_res)) {
        screen_free_lines(grid, &new_primary);
        return YETTY_ERR(yetty_ycore_void, "yvterm: resize alternate rect", alternate_res);
    }

    /* Blank fallback line at the new width — still fallible, so it happens
     * before the commit; on failure the old blank (and everything else)
     * stays. Committing a longer-than-needed blank is harmless. */
    struct yetty_ycore_void_result blank_res = grid_blank_line_resize(grid, cols);
    if (YETTY_IS_ERR(blank_res)) {
        screen_free_lines(grid, &new_primary);
        screen_free_lines(grid, &new_alternate);
        return YETTY_ERR(yetty_ycore_void, "yvterm: resize blank line", blank_res);
    }

    /* Commit point — everything below is infallible. */
    screen_free_lines(grid, &grid->primary);
    screen_free_lines(grid, &grid->alternate);
    grid->primary = new_primary;
    grid->alternate = new_alternate;
    grid->cols = cols;
    grid->visible_rows = rows;
    grid->cursor_row = reflow_cursor_row;
    grid->cursor_col = reflow_cursor_col;
    grid->selection_active = 0;

    /* Reflow re-bases the timeline numbering: end any scrolled-back view
     * here, at the single owner — consumers read the view state fresh on
     * every event, so no stale absolute index can be re-activated later. */
    grid->view_active = 0;
    grid->view_top = 0;
    grid->view_top_previous = 0;

    /* Geometry changed: rebuild the blank fallback line at the new width and
     * drop the materialization cache (its lines were expanded at the old
     * width; they re-inflate on the next scrolled-back frame). */
    for (uint32_t index = 0; index < YETTY_YVTERM_TIER_CACHE_ENTRIES; ++index) {
        struct yetty_yvterm_tier_cache_entry *entry = &grid->tiers.cache[index];
        if (entry->valid) {
            for (uint32_t line_index = 0; line_index < entry->line_count; ++line_index) {
                release_line_rich(&entry->lines[line_index]);
                free(entry->lines[line_index].text_cells);
            }
            free(entry->lines);
            entry->lines = NULL;
            entry->line_count = 0;
            entry->valid = 0;
        }
    }
    grid->window_count = 0;

    /* State adopts the new size + the reflowed cursor/continuation through
     * cb_resize. */
    vterm_set_size(grid->vterm, (int)rows, (int)cols);
    mark_dirty_all(grid);
    return YETTY_OK_VOID();
}

