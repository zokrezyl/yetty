static inline uint32_t pack_color(VTermColor color)
{
    return (uint32_t)color.red | ((uint32_t)color.green << 8) | ((uint32_t)color.blue << 16) |
           (0xFFu << 24);
}

/* Initial history capacity of the primary ring. The ring grows exponentially
 * (doubling in screen_grow_ring) toward visible_rows + the hot-window depth
 * as scrollback actually fills. A fresh terminal must NOT pre-commit the
 * configured maximum: a large hot-window config would otherwise eagerly
 * allocate (and blank) the whole ring at create. */
#define YVTERM_SCROLLBACK_INITIAL_ROWS 256u

/* Default hot-window depth (ring history lines whose anchored figures stay
 * fully materialized) when no config value is supplied. The live depth is
 * grid->hot_rows, set at create from the `scrollback/hot-lines` config key. */
#define YVTERM_HOT_ROWS_DEFAULT 2000u

/* Default warm-tier byte budget (lz4-compressed archive segments held in RAM
 * before spilling to the session-scoped cold file). Config:
 * scrollback/warm-bytes. */
#define YVTERM_WARM_BYTES_DEFAULT (64u * 1024u * 1024u)

/* The live screen buffer: the alternate ring while the alt-screen mode is on,
 * the primary ring otherwise. All libvterm callbacks and the visible-row /
 * raw-slot accessors resolve through this. */
static inline struct yetty_yvterm_screen *active_screen(struct yetty_yvterm_grid *grid)
{
    return grid->alt_screen ? &grid->alternate : &grid->primary;
}

/* Map a visible row [0, visible_rows) to its slot in a screen's line ring. The
 * primary ring spans line_count = visible_rows + scrollback, so the modulo is
 * over the FULL ring (not visible_rows) — that is what keeps rolled-off
 * history addressable. (The alternate ring has line_count == visible_rows.) */
static inline uint32_t screen_ring_slot(const struct yetty_yvterm_screen *screen, uint32_t row)
{
    if (!screen->line_count) {
        return row;
    }
    uint32_t slot = screen->base + row;
    while (slot >= screen->line_count) {
        slot -= screen->line_count;
    }
    return slot;
}

static inline struct yetty_yvterm_line *screen_line_at(struct yetty_yvterm_screen *screen,
                                                       uint32_t row)
{
    return &screen->lines[screen_ring_slot(screen, row)];
}

static inline struct yetty_yvterm_line *line_at(struct yetty_yvterm_grid *grid, uint32_t row)
{
    return screen_line_at(active_screen(grid), row);
}

static inline struct yetty_yvterm_text_cell *cell_at(struct yetty_yvterm_grid *grid, uint32_t row,
                                                     uint32_t col)
{
    return &line_at(grid, row)->text_cells[col];
}

static void destroy_composite(struct yetty_ydraw_composite *composite)
{
    if (composite) {
        yetty_ydraw_composite_destroy(composite);
    }
}

/* Growable backing arrays — each grows capacity (doubling, clamped to need). */

static struct yetty_ycore_void_result ensure_arena(struct yetty_yvterm_line *line, uint32_t need)
{
    if (need <= line->arena_capacity) {
        return YETTY_OK_VOID();
    }
    uint32_t new_cap = line->arena_capacity ? line->arena_capacity : 16u;
    while (new_cap < need) {
        new_cap *= 2u;
    }
    uint32_t *grown = realloc(line->arena, (size_t)new_cap * sizeof(*grown));
    if (!grown) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: arena grow failed");
    }
    line->arena = grown;
    line->arena_capacity = new_cap;
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result ensure_primitives(struct yetty_yvterm_line *line,
                                                        uint32_t need)
{
    if (need <= line->primitive_capacity) {
        return YETTY_OK_VOID();
    }
    uint32_t new_cap = line->primitive_capacity ? line->primitive_capacity : 4u;
    while (new_cap < need) {
        new_cap *= 2u;
    }
    struct yetty_yvterm_primitive *grown =
        realloc(line->primitives, (size_t)new_cap * sizeof(*grown));
    if (!grown) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: primitives grow failed");
    }
    line->primitives = grown;
    line->primitive_capacity = new_cap;
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result ensure_composites(struct yetty_yvterm_line *line,
                                                        uint32_t need)
{
    if (need <= line->composite_capacity) {
        return YETTY_OK_VOID();
    }
    uint32_t new_cap = line->composite_capacity ? line->composite_capacity : 4u;
    while (new_cap < need) {
        new_cap *= 2u;
    }
    struct yetty_ydraw_composite **grown =
        realloc(line->composites, (size_t)new_cap * sizeof(struct yetty_ydraw_composite *));
    if (!grown) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: composites grow failed");
    }
    line->composites = grown;
    line->composite_capacity = new_cap;
    return YETTY_OK_VOID();
}

/* Full line clear: release the line's owned rich content (arena/primitives
 * reset, composites destroyed). */
static void clear_line_rich(struct yetty_yvterm_line *line, uint32_t cols)
{
    (void)cols;
    line->primitive_count = 0;
    line->arena_count = 0;
    for (uint32_t i = 0; i < line->composite_count; ++i) {
        destroy_composite(line->composites[i]);
        line->composites[i] = NULL;
    }
    line->composite_count = 0;
    line->rich_span_rows = 0;
    line->envelope_count = 0;
    line->view_stamp = 0;
}

/* Evict a line's figure RUNTIMES only: destroy the composite instances but
 * keep everything serial — the arena (which holds the creating envelopes),
 * the primitive descriptors, and rich_span_rows (the renderer still needs the
 * block height to place re-materialized figures). This is the hot-tier
 * age-out: the expensive derived state (decoded pixels, GPU binders, video
 * decoder + coroutine + timer subscription) goes away, the wire truth stays. */
static void evict_line_figures(struct yetty_yvterm_line *line)
{
    for (uint32_t i = 0; i < line->composite_count; ++i) {
        destroy_composite(line->composites[i]);
        line->composites[i] = NULL;
    }
    line->composite_count = 0;
    line->view_stamp = 0;
}

/* Defined just below; the tier-engine wrappers reference it first. */
static void release_line_rich(struct yetty_yvterm_line *line);

/* Line helpers for the tier engine (scroll-tiers.c), which cannot reach the
 * static helpers above. */
void yetty_yvterm_line_release_rich(struct yetty_yvterm_line *line)
{
    release_line_rich(line);
}

void yetty_yvterm_line_evict_figures(struct yetty_yvterm_line *line)
{
    evict_line_figures(line);
}

/* Ring line for a row measured from the visible top, where `row` may be negative
 * to address retained scrollback history (row -1 is the line just above the
 * screen). The modulo spans the full ring so history slots resolve correctly. */
static struct yetty_yvterm_line *screen_line_at_signed(struct yetty_yvterm_screen *screen, int row)
{
    int64_t count = (int64_t)screen->line_count;
    int64_t slot = ((int64_t)screen->base + row) % count;
    if (slot < 0) {
        slot += count;
    }
    return &screen->lines[slot];
}

/* Retained ring history rows of a screen (clamped by ring capacity). */
static uint32_t screen_history_rows(const struct yetty_yvterm_grid *grid,
                                    const struct yetty_yvterm_screen *screen)
{
    uint32_t capacity =
        screen->line_count > grid->visible_rows ? screen->line_count - grid->visible_rows : 0u;
    return screen->total_scrolled < capacity ? (uint32_t)screen->total_scrolled : capacity;
}

/* Whether recycled primary-ring lines flow into the archive: with a total cap
 * at or below the ring's own history capacity the archive can never hold
 * anything reachable, so recycling drops lines exactly as before tiering.
 * (Defined ahead of the timeline helpers that branch on it.) */
static int grid_archive_enabled(const struct yetty_yvterm_grid *grid);

/* Timeline index of the ACTIVE screen's top visible row. For the primary
 * screen the timeline spans the archive + ring; the alternate screen has no
 * archive, so its own scroll origin doubles as its timeline. With the archive
 * disabled the ring's own scroll origin is the timeline (pre-tiering
 * semantics — recycled lines just vanish). */
static uint64_t grid_live_top_timeline(struct yetty_yvterm_grid *grid)
{
    struct yetty_yvterm_screen *screen = active_screen(grid);
    if (screen != &grid->primary) {
        return screen->total_scrolled;
    }
    if (!grid_archive_enabled(grid)) {
        return screen->total_scrolled;
    }
    return grid->tiers.archived_lines + screen_history_rows(grid, screen);
}

/* Defined in the reflow section below; used by the archive path too. */
static uint32_t line_used_cols(const struct yetty_yvterm_line *line, uint32_t cols);

/* Defined in the tiered-view section below; selection resolves through it
 * when a scrolled-back view is active. */
static struct yetty_yvterm_line *grid_resolve_view_row(struct yetty_yvterm_grid *grid,
                                                       uint64_t view_top, uint32_t row,
                                                       uint32_t *out_ring_slot, int *out_is_ring);

/* Serialize one ring line about to be recycled into the archive: destroy its
 * figure runtimes (envelopes stay in the arena), push the serial form, and
 * advance the timeline. Push failures degrade to dropping the line (pre-
 * tiering semantics) — the error is absorbed after tracing. */
static void grid_archive_recycled_line(struct yetty_yvterm_grid *grid,
                                       struct yetty_yvterm_line *line)
{
    if (line->composite_count) {
        evict_line_figures(line);
    }
    uint32_t used_cols = line_used_cols(line, grid->cols);
    /* Retained-top reference for the total-line cap: this line's timeline
     * index + 1 (it just aged out) + whatever the ring still retains. */
    uint64_t retained_top =
        grid->tiers.archived_lines + 1u + screen_history_rows(grid, &grid->primary);
    struct yetty_ycore_void_result push_res =
        yetty_yvterm_tiers_push_line(&grid->tiers, line, used_cols, grid->cols, retained_top);
    if (YETTY_IS_ERR(push_res)) {
        ywarn("scroll tiers: archiving a line failed (%s) — open segment dropped",
              push_res.error.msg);
        yetty_ycore_error_destroy(push_res.error);
        /* Keep the timeline contiguous and the open segment aligned: drop the
         * builder's partial lines along with this one (the resolver serves
         * blanks for the hole — no segment covers those indices). Only OOM
         * lands here. */
        struct yetty_yvterm_tier_builder *builder = &grid->tiers.builder;
        if (grid->tiers.warm_bytes_used >= builder->byte_count) {
            grid->tiers.warm_bytes_used -= builder->byte_count;
        }
        builder->byte_count = 0;
        builder->line_count = 0;
        grid->tiers.archived_lines++;
        builder->first_line = grid->tiers.archived_lines;
    }
}

/* Whether recycled primary-ring lines flow into the archive: with a total cap
 * at or below the ring's own history capacity the archive can never hold
 * anything reachable, so recycling drops lines exactly as before tiering. */
static int grid_archive_enabled(const struct yetty_yvterm_grid *grid)
{
    return grid->scrollback_rows == 0 || grid->scrollback_rows > grid->ring_history_cap;
}

/* Destroy a line's owned rich content AND free its backing arrays. Unlike
 * clear_line_rich (which keeps the arrays for reuse), this is for lines whose
 * backing is going away or is about to be replaced by pointer-move. */
static void release_line_rich(struct yetty_yvterm_line *line)
{
    for (uint32_t i = 0; i < line->composite_count; ++i) {
        destroy_composite(line->composites[i]);
    }
    free(line->composites);
    line->composites = NULL;
    line->composite_count = 0;
    line->composite_capacity = 0;
    free(line->primitives);
    line->primitives = NULL;
    line->primitive_count = 0;
    line->primitive_capacity = 0;
    free(line->arena);
    line->arena = NULL;
    line->arena_count = 0;
    line->arena_capacity = 0;
    line->rich_span_rows = 0;
    line->envelope_count = 0;
    line->view_stamp = 0;
}

static void blank_cell(struct yetty_yvterm_text_cell *cell, uint32_t fg, uint32_t bg)
{
    cell->glyph_index = 0;
    cell->codepoint = 0;
    cell->fg = fg;
    cell->bg = bg;
    cell->attrs = 0;
    cell->width = 1;
    cell->flags = 0;
}

/* Blank every cell of a line to the given fg/bg and release its rich content.
 * reset_line() uses the terminal default; erase (BCE) passes the pen colours.
 * cols is explicit (not grid->cols) because resize builds rings at the NEW
 * width while the grid still carries the old one. */
static void fill_line_blank(struct yetty_yvterm_line *line, uint32_t cols, uint32_t fg, uint32_t bg)
{
    for (uint32_t col = 0; col < cols; ++col) {
        blank_cell(&line->text_cells[col], fg, bg);
    }
    clear_line_rich(line, cols);
    line->continuation = 0;
}

static void reset_line(struct yetty_yvterm_grid *grid, struct yetty_yvterm_line *line)
{
    fill_line_blank(line, grid->cols, grid->default_fg, grid->default_bg);
}

static void mark_dirty_row(struct yetty_yvterm_grid *grid, uint32_t row)
{
    if (row >= grid->visible_rows) {
        return;
    }
    line_at(grid, row)->dirty = 1;
    grid->has_dirty = 1;
}

static void mark_dirty_all(struct yetty_yvterm_grid *grid)
{
    for (uint32_t i = 0; i < grid->primary.line_count; ++i) {
        grid->primary.lines[i].dirty = 1;
    }
    for (uint32_t i = 0; i < grid->alternate.line_count; ++i) {
        grid->alternate.lines[i].dirty = 1;
    }
    grid->has_dirty = 1;
}

/* Mirror libvterm's per-visible-row soft-wrap flag into the line ring after a
 * feed so resize reflow knows where logical lines wrap. libvterm sets
 * `continuation` by direct write (not via the setlineinfo callback), so it
 * cannot be observed incrementally; reading it for the whole visible window once
 * per feed keeps the on-screen rows exact. A line that becomes a continuation
 * and then scrolls off within a single bulk feed keeps whatever flag it last
 * carried while visible — at worst that under-marks deep scrollback, which makes
 * a paragraph keep its old wrap rather than corrupting anything. */
static void grid_sync_continuation(struct yetty_yvterm_grid *grid)
{
    if (!grid->state) {
        return;
    }
    for (uint32_t row = 0; row < grid->visible_rows; ++row) {
        const VTermLineInfo *info = vterm_state_get_lineinfo(grid->state, (int)row);
        line_at(grid, row)->continuation = (info && info->continuation) ? 1 : 0;
    }
}

/* Grow the primary ring so the next rolled-off rows land in fresh slots
 * instead of recycling live history. Doubles the ring (clamped to the
 * immediate need and to visible_rows + scrollback_rows). The surviving lines
 * are re-laid-out in LOGICAL order — oldest history at slot 0, visible rows
 * after it, base = history — so the fresh tail slots sit logically after the
 * newest line and the ring stays unwrapped until it is full again. Line
 * structs move by value; their owned buffers (cells/arena/composites) travel
 * with them. Best-effort: on allocation failure the ring is left untouched
 * and the caller recycles the oldest history line exactly as before. */
static void screen_grow_ring(struct yetty_yvterm_grid *grid, struct yetty_yvterm_screen *screen,
                             uint32_t needed_history)
{
    uint32_t visible = grid->visible_rows;
    uint32_t max_line_count = visible + grid->ring_history_cap;
    uint32_t old_count = screen->line_count;
    if (old_count >= max_line_count) {
        return;
    }
    if (needed_history > grid->ring_history_cap) {
        needed_history = grid->ring_history_cap;
    }
    uint32_t new_count = old_count > (UINT32_MAX / 2u) ? max_line_count : old_count * 2u;
    if (new_count < visible + needed_history) {
        new_count = visible + needed_history;
    }
    if (new_count > max_line_count) {
        new_count = max_line_count;
    }
    if (new_count <= old_count) {
        return;
    }

    struct yetty_yvterm_line *new_lines = calloc(new_count, sizeof(*new_lines));
    if (!new_lines) {
        return;
    }
    /* Allocate the fresh tail slots first so a failure backs out before any
     * existing line has moved. */
    for (uint32_t slot = old_count; slot < new_count; ++slot) {
        new_lines[slot].text_cells = yetty_ycore_memtag_calloc(
            &grid->ring_memtag, grid->cols, sizeof(struct yetty_yvterm_text_cell));
        if (!new_lines[slot].text_cells) {
            for (uint32_t undo = old_count; undo < slot; ++undo) {
                yetty_ycore_memtag_free(&grid->ring_memtag, new_lines[undo].text_cells);
            }
            free(new_lines);
            return;
        }
        fill_line_blank(&new_lines[slot], grid->cols, grid->default_fg, grid->default_bg);
    }

    /* Unwrap: logical index 0 is the oldest retained history line; the ring
     * bijection (base + logical − hist) mod old_count visits every old slot
     * exactly once, so allocated-but-unused slots (a ring that grew before
     * filling) carry over after the visible block. */
    uint32_t capacity = old_count - visible;
    uint32_t hist = screen->total_scrolled < capacity ? screen->total_scrolled : capacity;
    for (uint32_t logical = 0; logical < old_count; ++logical) {
        int64_t slot =
            ((int64_t)screen->base + (int64_t)logical - (int64_t)hist) % (int64_t)old_count;
        if (slot < 0) {
            slot += old_count;
        }
        new_lines[logical] = screen->lines[slot];
    }
    free(screen->lines);
    screen->lines = new_lines;
    screen->line_count = new_count;
    screen->base = hist;
}

/* O(1) whole-screen scroll-up of the ACTIVE screen. The rolled-off top lines
 * are NOT blanked — they stay in the ring as scrollback history (their GPU
 * cells persist for the scrolled-back view). Instead the freshly-exposed
 * bottom rows are blanked. On the primary ring (line_count = visible_rows +
 * scrollback) slot (base + visible_rows) aliases the oldest history slot, so
 * blanking it there naturally evicts the oldest line and reuses it as the new
 * blank bottom. On the alternate ring (line_count == visible_rows) the same
 * arithmetic blanks the line rolling off the top and reuses it as the new
 * bottom — an in-place rotation that retains nothing, which is exactly the
 * no-scrollback alternate-screen semantics. Advancing base moves the whole
 * view down by one row over the ring. */
static void roll_up(struct yetty_yvterm_grid *grid, uint32_t count)
{
    struct yetty_yvterm_screen *screen = active_screen(grid);
    if (grid->visible_rows == 0 || screen->line_count == 0) {
        return;
    }
    if (count > grid->visible_rows) {
        count = grid->visible_rows;
    }

    /* Primary ring only: when this roll would recycle history and the ring is
     * below its configured maximum, grow it instead (lazy scrollback). The
     * alternate ring never grows — it is visible-only by design. */
    if (screen == &grid->primary) {
        uint32_t capacity = screen->line_count - grid->visible_rows;
        uint64_t needed = (uint64_t)screen->total_scrolled + count;
        if (needed > capacity) {
            uint32_t needed_history =
                needed > grid->ring_history_cap ? grid->ring_history_cap : (uint32_t)needed;
            screen_grow_ring(grid, screen, needed_history);
        }
    }
    int archive = screen == &grid->primary && grid_archive_enabled(grid);
    uint32_t capacity_after_grow = screen->line_count - grid->visible_rows;
    for (uint32_t step = 0; step < count; ++step) {
        uint32_t slot = screen->base + grid->visible_rows + step;
        while (slot >= screen->line_count) {
            slot -= screen->line_count;
        }
        /* On a full primary ring this slot aliases the OLDEST history line —
         * the hot tier's age-out point. Serialize it into the archive before
         * the blank recycles it. */
        if (archive && (uint64_t)screen->total_scrolled + step + 1u > capacity_after_grow) {
            grid_archive_recycled_line(grid, &screen->lines[slot]);
        }
        reset_line(grid, &screen->lines[slot]);
        screen->lines[slot].dirty = 1;
    }
    screen->base += count;
    screen->total_scrolled += count; /* rolling-row origin advances with scroll */
    while (screen->base >= screen->line_count) {
        screen->base -= screen->line_count;
    }
    grid->has_dirty = 1;
}

/* Move one cell's text state. Line-owned primitive/composite storage is not
 * touched: it lives on its anchor line and scrolls with that line, so a
 * within-grid cell move (libvterm region scroll / DECSTBM) only relocates text. */
static void move_cell(struct yetty_yvterm_grid *grid, uint32_t dst_row, uint32_t dst_col,
                      uint32_t src_row, uint32_t src_col)
{
    *cell_at(grid, dst_row, dst_col) = *cell_at(grid, src_row, src_col);
}

