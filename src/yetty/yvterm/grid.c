/* Mirror libvterm's per-visible-row soft-wrap flag into the line ring after a
 * feed so resize reflow knows where logical lines wrap. libvterm sets
 * `continuation` by direct write (not via the setlineinfo callback), so it
 * cannot be observed incrementally; reading it for the whole visible window once
 * per feed keeps the on-screen rows exact. A line that becomes a continuation
 * and then scrolls off within a single bulk feed keeps whatever flag it last
 * carried while visible — at worst that under-marks deep scrollback, which makes
 * a paragraph keep its old wrap rather than corrupting anything. */
static void grid_sync_continuation(struct yetty_yvterm_grid *grid)
{
    if (!grid->state) {
        return;
    }
    for (uint32_t row = 0; row < grid->visible_rows; ++row) {
        const VTermLineInfo *info = vterm_state_get_lineinfo(grid->state, (int)row);
        line_at(grid, row)->continuation = (info && info->continuation) ? 1 : 0;
    }
}

/* Grow the primary ring so the next rolled-off rows land in fresh slots
 * instead of recycling live history. Doubles the ring (clamped to the
 * immediate need and to visible_rows + scrollback_rows). The surviving lines
 * are re-laid-out in LOGICAL order — oldest history at slot 0, visible rows
 * after it, base = history — so the fresh tail slots sit logically after the
 * newest line and the ring stays unwrapped until it is full again. Line
 * structs move by value; their owned buffers (cells/arena/complexes) travel
 * with them. Best-effort: on allocation failure the ring is left untouched
 * and the caller recycles the oldest history line exactly as before. */
static void screen_grow_ring(struct yetty_yvterm_grid *grid, struct yetty_yvterm_screen *screen,
                             uint32_t needed_history)
{
    uint32_t visible = grid->visible_rows;
    uint32_t max_line_count = visible + grid->ring_history_cap;
    uint32_t old_count = screen->line_count;
    if (old_count >= max_line_count) {
        return;
    }
    if (needed_history > grid->ring_history_cap) {
        needed_history = grid->ring_history_cap;
    }
    uint32_t new_count = old_count > (UINT32_MAX / 2u) ? max_line_count : old_count * 2u;
    if (new_count < visible + needed_history) {
        new_count = visible + needed_history;
    }
    if (new_count > max_line_count) {
        new_count = max_line_count;
    }
    if (new_count <= old_count) {
        return;
    }

    struct yetty_yvterm_line *new_lines = calloc(new_count, sizeof(*new_lines));
    if (!new_lines) {
        return;
    }
    /* Allocate the fresh tail slots first so a failure backs out before any
     * existing line has moved. */
    for (uint32_t slot = old_count; slot < new_count; ++slot) {
        new_lines[slot].text_cells = yetty_ycore_memtag_calloc(
            &grid->ring_memtag, grid->cols, sizeof(struct yetty_yvterm_text_cell));
        if (!new_lines[slot].text_cells) {
            for (uint32_t undo = old_count; undo < slot; ++undo) {
                yetty_ycore_memtag_free(&grid->ring_memtag, new_lines[undo].text_cells);
            }
            free(new_lines);
            return;
        }
        fill_line_blank(grid, &new_lines[slot], grid->cols, grid->default_fg, grid->default_bg);
    }

    /* Unwrap: logical index 0 is the oldest retained history line; the ring
     * bijection (base + logical − hist) mod old_count visits every old slot
     * exactly once, so allocated-but-unused slots (a ring that grew before
     * filling) carry over after the visible block. */
    uint32_t capacity = old_count - visible;
    uint32_t hist = screen->total_scrolled < capacity ? screen->total_scrolled : capacity;
    for (uint32_t logical = 0; logical < old_count; ++logical) {
        int64_t slot =
            ((int64_t)screen->base + (int64_t)logical - (int64_t)hist) % (int64_t)old_count;
        if (slot < 0) {
            slot += old_count;
        }
        new_lines[logical] = screen->lines[slot];
    }
    free(screen->lines);
    screen->lines = new_lines;
    screen->line_count = new_count;
    screen->base = hist;
}

/* O(1) whole-screen scroll-up of the ACTIVE screen. The rolled-off top lines
 * are NOT blanked — they stay in the ring as scrollback history (their GPU
 * cells persist for the scrolled-back view). Instead the freshly-exposed
 * bottom rows are blanked. On the primary ring (line_count = visible_rows +
 * scrollback) slot (base + visible_rows) aliases the oldest history slot, so
 * blanking it there naturally evicts the oldest line and reuses it as the new
 * blank bottom. On the alternate ring (line_count == visible_rows) the same
 * arithmetic blanks the line rolling off the top and reuses it as the new
 * bottom — an in-place rotation that retains nothing, which is exactly the
 * no-scrollback alternate-screen semantics. Advancing base moves the whole
 * view down by one row over the ring. */
/* Sum of the group-chain vertical offsets above (and including) the
 * record's scope — the projection the renderer applies. Cycle-guarded. */
static float record_chain_offset_y(const struct yetty_yvterm_rich_block *block, uint32_t group_slot)
{
    float sum = 0.0f;
    uint32_t guard = 0;
    while (group_slot != 0 && group_slot <= block->group_count && guard++ <= block->group_count) {
        sum += block->groups[group_slot - 1u].offset_y;
        group_slot = block->groups[group_slot - 1u].parent_slot;
    }
    return sum;
}

/* Per-node scroll retirement (UC-12): permanently retire every addressable
 * node of a still-live block whose CURRENT projected footprint lies
 * entirely above the new live top. A node's footprint is the union of its
 * subtree's known record extents plus accumulated ancestor offsets,
 * clamped to the insertion span. DETACHED content (projected outside the
 * span) and unknown-extent records EXEMPT their node — out of view is not
 * out of scope, and conservative beats wrongly killing an id. Evaluated
 * only at terminal-scroll time, so offsets alone never retire anything;
 * partial visibility keeps the whole node addressable (the half-scrolled
 * streaming plot). Idempotent — re-scanning retires the same set. */
static void grid_retire_departed_nodes(struct yetty_yvterm_grid *grid,
                                       struct yetty_yvterm_rich_block *block, uint64_t new_live_top)
{
    float cell_h = grid->cell_height_px;
    if (cell_h <= 0.0f) {
        return; /* no metrics yet — retire nothing */
    }
    uint32_t span = block->span_rows ? block->span_rows : 1u;
    float span_px = (float)span * cell_h;
    /* Per-group subtree fold: ONE pass over the records computes each
     * projected footprint once and folds it up the record's ancestor
     * chain — O(records x chain + groups), replacing the old
     * per-group-times-per-record rescan. A failed scratch allocation
     * skips only the GROUP half for this sweep (records still retire;
     * groups catch up on the next scroll — retirement is idempotent). */
    struct grid_retire_fold {
        uint32_t max_last_relative;
        uint8_t attached;
        uint8_t unknown;
    };
    struct grid_retire_fold *fold =
        block->group_count ? calloc(block->group_count, sizeof(struct grid_retire_fold)) : NULL;
    for (uint32_t index = 0; index < block->record_count; ++index) {
        struct yetty_yvterm_rich_record *record = &block->records[index];
        if (!record->alive || !record->render_leaf) {
            continue;
        }
        if (!record->extent_known) {
            /* Unknown extent exempts the record AND every ancestor group
             * (conservative beats wrongly killing an id). */
            uint32_t walk = record->group_slot;
            uint32_t guard = 0;
            while (fold && walk != 0 && walk <= block->group_count &&
                   guard++ <= block->group_count) {
                if (fold[walk - 1u].unknown) {
                    break;
                }
                fold[walk - 1u].unknown = 1;
                walk = block->groups[walk - 1u].parent_slot;
            }
            continue;
        }
        /* Footprints and chain offsets are PRODUCER-LOGICAL pixels;
         * span_px/cell_h are framebuffer pixels — scale by the committed
         * density before comparing (at scale 2 an unscaled 300px extent
         * would retire ~10 rows early). */
        float density = grid->rich_density_scale > 0.0f ? grid->rich_density_scale : 1.0f;
        float chain_offset = record_chain_offset_y(block, record->group_slot);
        float top = (record->content_top_px + chain_offset) * density;
        float bottom = (record->content_bottom_px + chain_offset) * density;
        if (bottom <= 0.0f || top >= span_px) {
            continue; /* detached — exempt (record and subtree union alike) */
        }
        float clamped_bottom = bottom < span_px ? bottom : span_px;
        /* Last footprint row = ceil(bottom / cell_h) - 1: a bottom edge
         * anywhere inside row N (boundary included, per the use-cases
         * rule) keeps row N in the footprint. clamped_bottom > 0 here, so
         * ceilf >= 1 and the subtraction stays in range — no epsilon, no
         * negative-to-unsigned conversion. */
        uint32_t last_relative = (uint32_t)ceilf(clamped_bottom / cell_h) - 1u;
        if (last_relative >= span) {
            last_relative = span - 1u;
        }
        /* Records retire on their OWN footprint (an id-bearing complex is
         * addressable through its record; retiring unbound records is
         * harmless). */
        if (!record->retired && block->insertion_rolling_row + last_relative < new_live_top) {
            record->retired = true;
        }
        uint32_t walk = record->group_slot;
        uint32_t guard = 0;
        while (fold && walk != 0 && walk <= block->group_count && guard++ <= block->group_count) {
            struct grid_retire_fold *entry = &fold[walk - 1u];
            entry->attached = 1;
            if (last_relative > entry->max_last_relative) {
                entry->max_last_relative = last_relative;
            }
            walk = block->groups[walk - 1u].parent_slot;
        }
    }
    /* Groups retire on their folded subtree UNION. */
    for (uint32_t group_index = 0; fold && group_index < block->group_count; ++group_index) {
        struct yetty_yvterm_rich_group *group = &block->groups[group_index];
        if (!group->alive || group->retired ||
            yetty_yvterm_rich_block_group_chain_retired(block, group_index + 1u)) {
            continue; /* dead, already frozen, or under a frozen ancestor */
        }
        const struct grid_retire_fold *entry = &fold[group_index];
        if (entry->unknown || !entry->attached) {
            continue; /* conservative / detached-or-empty — exempt */
        }
        if (block->insertion_rolling_row + entry->max_last_relative < new_live_top) {
            group->retired = true;
        }
    }
    free(fold);
}

/* Seal every live block whose WHOLE span is about to cross the live top,
 * and run per-node retirement on the still-live blocks that partially
 * cross: from the seal the content is recorded history and must not
 * change; from a node retirement that NODE is. Metadata only — placement,
 * records and renderability are untouched. Proportional to the blocks
 * actually crossing: only the `count` departing rows are scanned, gated by
 * their coverage counters. Runs for the ACTIVE screen; sealing (history)
 * exists on the primary only, retirement applies to both. */
static void grid_seal_crossing_blocks(struct yetty_yvterm_grid *grid, uint32_t count)
{
    struct yetty_yvterm_screen *screen = active_screen(grid);
    int primary = screen == &grid->primary;
    enum yetty_yvterm_rich_block_screen want_screen =
        primary ? YETTY_YVTERM_RICH_SCREEN_PRIMARY : YETTY_YVTERM_RICH_SCREEN_ALTERNATE;
    uint64_t new_live_top = screen->total_scrolled + count;
    /* One retirement sweep per block per batch: every departing covered
     * row reaches the same block, and the scan is idempotent. */
    grid->retire_sweep_id++;
    uint32_t walk_limit = grid->max_resident_span ? grid->max_resident_span : 1u;
    for (uint32_t row = 0; row < count && row < grid->visible_rows; ++row) {
        if (screen_line_at(screen, row)->rich_coverage_count == 0) {
            continue;
        }
        uint64_t target_timeline = screen->total_scrolled + row;
        for (uint32_t offset = 0; offset < walk_limit; ++offset) {
            uint32_t owner_row = row + offset;
            if (owner_row >= grid->visible_rows) {
                break;
            }
            struct yetty_yvterm_line *line = screen_line_at(screen, owner_row);
            for (uint32_t index = 0; index < line->rich_block_count; ++index) {
                struct yetty_yvterm_rich_block *block =
                    yetty_yvterm_rich_store_resolve(&grid->rich_store, line->rich_blocks[index]);
                if (!block || block->state != YETTY_YVTERM_RICH_BLOCK_LIVE ||
                    block->screen != want_screen) {
                    continue;
                }
                uint32_t span = block->span_rows ? block->span_rows : 1u;
                uint64_t top = block->insertion_rolling_row;
                if (target_timeline < top || target_timeline > top + span - 1u) {
                    continue;
                }
                /* Seal only when the WHOLE block has left the visible area
                 * (its BOTTOM row crossed above the new live top) — a block
                 * still PARTIALLY on screen stays LIVE, and its nodes
                 * retire individually by footprint instead. */
                if (primary && top + span - 1u < new_live_top) {
                    block->state = YETTY_YVTERM_RICH_BLOCK_SEALED;
                } else if (block->retire_sweep_stamp != grid->retire_sweep_id) {
                    block->retire_sweep_stamp = grid->retire_sweep_id;
                    grid_retire_departed_nodes(grid, block, new_live_top);
                }
            }
        }
    }
}

/* Destroy every rich block whose vertical span covers visible row `row` —
 * the block-granular invalidation rule: a write or erase intersecting ANY
 * covered row removes the complete block and (later) all of its live
 * bindings; no partially addressable remnant survives. The per-line coverage
 * counter is the required constant-time gate: ordinary text output on
 * uncovered rows never probes the block walk. Handle removal is ordered
 * (memmove) so the surviving blocks keep their paint order. */
static void grid_invalidate_rich_at_row(struct yetty_yvterm_grid *grid, uint32_t row)
{
    struct yetty_yvterm_screen *screen = active_screen(grid);
    if (row >= grid->visible_rows || screen_line_at(screen, row)->rich_coverage_count == 0) {
        return;
    }
    uint64_t target_timeline = screen->total_scrolled + row;
    uint32_t walk_limit = grid->max_resident_span ? grid->max_resident_span : 1u;
    for (uint32_t offset = 0; offset < walk_limit; ++offset) {
        uint32_t owner_row = row + offset;
        if (owner_row >= grid->visible_rows) {
            break;
        }
        struct yetty_yvterm_line *line = screen_line_at(screen, owner_row);
        uint32_t index = 0;
        while (index < line->rich_block_count) {
            struct yetty_yvterm_rich_block *block =
                yetty_yvterm_rich_store_resolve(&grid->rich_store, line->rich_blocks[index]);
            int remove = 0;
            if (!block) {
                remove = 1; /* stale handle — drop it */
            } else {
                uint32_t span = block->span_rows ? block->span_rows : 1u;
                uint64_t top = block->insertion_rolling_row;
                if (target_timeline >= top && target_timeline <= top + span - 1u) {
                    grid_block_coverage_adjust(grid, block, -1);
                    yetty_yvterm_rich_store_block_destroy(&grid->rich_store,
                                                          line->rich_blocks[index]);
                    remove = 1;
                    mark_dirty_row(grid, owner_row);
                }
            }
            if (remove) {
                memmove(&line->rich_blocks[index], &line->rich_blocks[index + 1u],
                        (size_t)(line->rich_block_count - index - 1u) *
                            sizeof(struct yetty_yvterm_rich_handle));
                line->rich_block_count--;
            } else {
                index++;
            }
        }
    }
}

static uint32_t grid_binding_hash(uint64_t group_key)
{
    uint64_t hash = yetty_yvterm_group_mix64(group_key);
    return (uint32_t)(hash ^ (hash >> 32));
}

static struct yetty_yvterm_rich_binding *grid_binding_probe(struct yetty_yvterm_grid *grid,
                                                            uint64_t group_key, int for_insert)
{
    if (!grid->group_binding_capacity) {
        return NULL;
    }
    uint32_t mask = grid->group_binding_capacity - 1u;
    uint32_t index = grid_binding_hash(group_key) & mask;
    struct yetty_yvterm_rich_binding *first_tombstone = NULL;
    for (uint32_t probe = 0; probe <= mask; ++probe, index = (index + 1u) & mask) {
        struct yetty_yvterm_rich_binding *entry = &grid->group_bindings[index];
        if (entry->state == YVTERM_BINDING_LIVE && entry->group_key == group_key) {
            return entry;
        }
        if (entry->state == YVTERM_BINDING_EMPTY) {
            return for_insert ? (first_tombstone ? first_tombstone : entry) : NULL;
        }
        if (entry->state == YVTERM_BINDING_TOMBSTONE && !first_tombstone) {
            first_tombstone = entry;
        }
    }
    return for_insert ? first_tombstone : NULL;
}

static int grid_binding_valid(struct yetty_yvterm_grid *grid,
                              const struct yetty_yvterm_rich_binding *entry);

/* Rebuild the binding table at `new_capacity`: tombstones vanish and any
 * LIVE entry that no longer validates (dead target, recycled group slot,
 * sealed block) is dropped. */
static struct yetty_ycore_void_result grid_binding_rebuild(struct yetty_yvterm_grid *grid,
                                                           uint32_t new_capacity)
{
    struct yetty_yvterm_rich_binding *grown =
        calloc(new_capacity, sizeof(struct yetty_yvterm_rich_binding));
    if (!grown) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: group binding table grow failed");
    }
    struct yetty_yvterm_rich_binding *old_table = grid->group_bindings;
    uint32_t old_capacity = grid->group_binding_capacity;
    grid->group_bindings = grown;
    grid->group_binding_capacity = new_capacity;
    grid->group_binding_count = 0;
    for (uint32_t index = 0; index < old_capacity; ++index) {
        if (old_table[index].state == YVTERM_BINDING_LIVE &&
            grid_binding_valid(grid, &old_table[index])) {
            struct yetty_yvterm_rich_binding *rehomed =
                grid_binding_probe(grid, old_table[index].group_key, 1);
            *rehomed = old_table[index];
            grid->group_binding_count++;
        }
    }
    free(old_table);
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result grid_binding_put(struct yetty_yvterm_grid *grid,
                                                       uint64_t group_key, uint8_t node_kind,
                                                       struct yetty_yvterm_rich_handle block,
                                                       uint32_t slot)
{
    if ((grid->group_binding_count + 1u) * 2u >= grid->group_binding_capacity) {
        /* The density trigger is the amortized SWEEP point: replacement
         * patterns that create no dead drawable records (pure group-tree
         * churn with fresh ids) never trip the record-compaction sweep,
         * so stale entries are dropped HERE. Rebuild at the SAME capacity
         * when the survivors fit (garbage, not genuine growth — the
         * capacity must stay O(valid), never ratchet on churn); double
         * only when valid density really demands it. */
        uint32_t survivors = 0;
        for (uint32_t index = 0; index < grid->group_binding_capacity; ++index) {
            if (grid->group_bindings[index].state == YVTERM_BINDING_LIVE &&
                grid_binding_valid(grid, &grid->group_bindings[index])) {
                survivors++;
            }
        }
        uint32_t new_capacity = grid->group_binding_capacity ? grid->group_binding_capacity : 16u;
        while ((survivors + 1u) * 2u >= new_capacity) {
            new_capacity *= 2u;
        }
        struct yetty_ycore_void_result rebuild_res = grid_binding_rebuild(grid, new_capacity);
        YETTY_RETURN_IF_ERR(yetty_ycore_void, rebuild_res, "yvterm: binding rebuild");
    }
    struct yetty_yvterm_rich_binding *entry = grid_binding_probe(grid, group_key, 1);
    if (!entry) {
        return YETTY_ERR(yetty_ycore_void, "yvterm: group binding table full");
    }
    if (entry->state != YVTERM_BINDING_LIVE) {
        grid->group_binding_count++;
    }
    entry->state = YVTERM_BINDING_LIVE;
    entry->node_kind = node_kind;
    entry->group_key = group_key;
    entry->block = block;
    entry->slot = slot;
    entry->group_generation = 0;
    if (node_kind == YVTERM_NODE_GROUP) {
        /* Stamp the occupant's reuse generation so a recycled slot can
         * never satisfy this (by then stale) binding. */
        struct yetty_yvterm_rich_block *bound_block =
            yetty_yvterm_rich_store_resolve(&grid->rich_store, block);
        if (bound_block && slot >= 1u && slot <= bound_block->group_count) {
            entry->group_generation = bound_block->groups[slot - 1u].generation;
        }
    }
    return YETTY_OK_VOID();
}

static void grid_binding_remove(struct yetty_yvterm_grid *grid,
                                struct yetty_yvterm_rich_binding *entry)
{
    entry->state = YVTERM_BINDING_TOMBSTONE;
    if (grid->group_binding_count) {
        grid->group_binding_count--;
    }
}

static int grid_binding_valid(struct yetty_yvterm_grid *grid,
                              const struct yetty_yvterm_rich_binding *entry);

/* Live reclamation of replacement garbage: every in-place group reopen
 * (skin repaints, receiver-local chrome rebuilds) appends a fresh record
 * generation and merely kills the old one, and a fullscreen insertion can
 * stay live for hours — without this, retained memory AND every
 * record-table scan (retirement, paint plan) would grow with the number
 * of updates instead of the amount of live content. Compact when the
 * dead share dominates (amortized O(1) per replacement, bounding the
 * table near 2x the live size), then remap the COMPLEX bindings that
 * address records by index. The same cadence SWEEPS the binding table:
 * entries whose targets died (or whose group slot was recycled) are
 * otherwise purged only if their exact path happens to be queried again,
 * and rehashing carries such garbage forever. Skipping on a failed
 * scratch allocation is safe — the next close tries again. */
static void grid_maybe_compact_block(struct yetty_yvterm_grid *grid,
                                     struct yetty_yvterm_rich_handle handle)
{
    enum { GRID_COMPACT_DEAD_FLOOR = 32 };
    struct yetty_yvterm_rich_block *block =
        yetty_yvterm_rich_store_resolve(&grid->rich_store, handle);
    if (!block) {
        return;
    }
    uint32_t dead = yetty_yvterm_rich_store_block_dead_records(&grid->rich_store, handle);
    if (dead < (uint32_t)GRID_COMPACT_DEAD_FLOOR || dead * 2u < block->record_count) {
        return;
    }
    uint32_t old_count = block->record_count;
    uint32_t *remap = malloc((size_t)old_count * sizeof(uint32_t));
    if (!remap) {
        return;
    }
    uint32_t dropped =
        yetty_yvterm_rich_store_block_compact(&grid->rich_store, handle, remap, old_count);
    if (dropped) {
        for (uint32_t index = 0; index < grid->group_binding_capacity; ++index) {
            struct yetty_yvterm_rich_binding *entry = &grid->group_bindings[index];
            if (entry->state != YVTERM_BINDING_LIVE || entry->node_kind != YVTERM_NODE_COMPLEX ||
                entry->block.slot != handle.slot || entry->block.generation != handle.generation) {
                continue;
            }
            uint32_t new_slot = entry->slot < old_count ? remap[entry->slot] : UINT32_MAX;
            if (new_slot == UINT32_MAX) {
                grid_binding_remove(grid, entry); /* was bound to a dead record */
            } else {
                entry->slot = new_slot;
            }
        }
    }
    free(remap);
    /* Purge every binding that no longer validates — dead targets, sealed
     * blocks, recycled group slots. Amortized at the compaction cadence. */
    for (uint32_t index = 0; index < grid->group_binding_capacity; ++index) {
        struct yetty_yvterm_rich_binding *entry = &grid->group_bindings[index];
        if (entry->state == YVTERM_BINDING_LIVE && !grid_binding_valid(grid, entry)) {
            grid_binding_remove(grid, entry);
        }
    }
}

/* Whether a LIVE binding entry still resolves to the node it was bound
 * to — the one validation shared by lookup (grid_binding_live) and the
 * reclamation sweep. */
static int grid_binding_valid(struct yetty_yvterm_grid *grid,
                              const struct yetty_yvterm_rich_binding *entry)
{
    struct yetty_yvterm_rich_block *block =
        yetty_yvterm_rich_store_resolve(&grid->rich_store, entry->block);
    if (!block || block->state != YETTY_YVTERM_RICH_BLOCK_LIVE) {
        return 0;
    }
    if (entry->node_kind == YVTERM_NODE_COMPLEX) {
        /* Complex node: the slot field is a record index. A retired record
         * (its own footprint left the surface) or one under a retired group
         * is frozen history — permanently unaddressable. */
        if (entry->slot >= block->record_count || !block->records[entry->slot].alive ||
            block->records[entry->slot].retired ||
            yetty_yvterm_rich_block_group_chain_retired(block,
                                                        block->records[entry->slot].group_slot)) {
            return 0;
        }
        return 1;
    }
    if (yetty_yvterm_rich_block_group_dead(block, entry->slot) ||
        yetty_yvterm_rich_block_group_chain_retired(block, entry->slot)) {
        return 0;
    }
    /* The slot may have been RECYCLED for a fresh group since this path
     * was bound — the occupant's generation must still match. */
    if (entry->slot >= 1u && entry->slot <= block->group_count &&
        block->groups[entry->slot - 1u].generation != entry->group_generation) {
        return 0;
    }
    return 1;
}

/* The LIVE node binding for a path key, or NULL. Stale and sealed targets are
 * purged here — this is where "entering primary scrollback removes
 * addressability" becomes observable, and why a reused path never collides
 * with history. */
static struct yetty_yvterm_rich_binding *grid_binding_live(struct yetty_yvterm_grid *grid,
                                                           uint64_t group_key)
{
    struct yetty_yvterm_rich_binding *entry = grid_binding_probe(grid, group_key, 0);
    if (!entry) {
        return NULL;
    }
    if (!grid_binding_valid(grid, entry)) {
        grid_binding_remove(grid, entry);
        return NULL;
    }
    return entry;
}

static void roll_up(struct yetty_yvterm_grid *grid, uint32_t count)
{
    struct yetty_yvterm_screen *screen = active_screen(grid);
    if (grid->visible_rows == 0 || screen->line_count == 0) {
        return;
    }
    if (count > grid->visible_rows) {
        count = grid->visible_rows;
    }
    /* Whole-block sealing (primary) + per-node retirement (both screens). */
    grid_seal_crossing_blocks(grid, count);

    /* Primary ring only: when this roll would recycle history and the ring is
     * below its configured maximum, grow it instead (lazy scrollback). The
     * alternate ring never grows — it is visible-only by design.
     *
     * Size the ring from the RING-LOCAL history depth, not the archive-
     * inclusive total_scrolled: after a resize drains history into the archive
     * the ring is rebuilt with near-zero local history, and feeding the
     * lifetime scroll count here would immediately regrow it to
     * ring_history_cap — defeating lazy scrollback. total_scrolled is for
     * timeline coordinates; ring sizing uses the local history. */
    if (screen == &grid->primary) {
        uint32_t capacity = screen->line_count - grid->visible_rows;
        uint64_t needed = (uint64_t)screen_history_rows(grid, screen) + count;
        if (needed > capacity) {
            uint32_t needed_history =
                needed > grid->ring_history_cap ? grid->ring_history_cap : (uint32_t)needed;
            screen_grow_ring(grid, screen, needed_history);
        }
    }
    int archive = screen == &grid->primary && grid_archive_enabled(grid);
    uint32_t capacity_after_grow = screen->line_count - grid->visible_rows;
    for (uint32_t step = 0; step < count; ++step) {
        uint32_t slot = screen->base + grid->visible_rows + step;
        while (slot >= screen->line_count) {
            slot -= screen->line_count;
        }
        /* On a full primary ring this slot aliases the OLDEST history line —
         * the hot tier's age-out point. Serialize it into the archive before
         * the blank recycles it. */
        if (archive && (uint64_t)screen->total_scrolled + step + 1u > capacity_after_grow) {
            grid_archive_recycled_line(grid, &screen->lines[slot]);
        }
        reset_line(grid, &screen->lines[slot]);
        screen->lines[slot].dirty = 1;
    }
    screen->base += count;
    screen->total_scrolled += count; /* rolling-row origin advances with scroll */
    while (screen->base >= screen->line_count) {
        screen->base -= screen->line_count;
    }
    if (grid->batch_block_valid) {
        grid->batch_block_row -= (int)count; /* the handle's line moved with the scroll */
    }
    grid->has_dirty = 1;
}

/* Move one cell's text state. Line-owned primitive/complex storage is not
 * touched: it lives on its anchor line and scrolls with that line, so a
 * within-grid cell move (libvterm region scroll / DECSTBM) only relocates text. */
static void move_cell(struct yetty_yvterm_grid *grid, uint32_t dst_row, uint32_t dst_col,
                      uint32_t src_row, uint32_t src_col)
{
    *cell_at(grid, dst_row, dst_col) = *cell_at(grid, src_row, src_col);
}

