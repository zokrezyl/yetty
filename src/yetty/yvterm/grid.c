/* One live external-id binding: see the group_bindings field. Slot state,
 * key kind, namespace and id are all EXPLICIT fields — no packed-key bit
 * tricks, so no namespace can collide with another key space or with a
 * table sentinel. */
enum yetty_yvterm_rich_binding_state {
    YVTERM_BINDING_EMPTY = 0,
    YVTERM_BINDING_LIVE = 1,
    YVTERM_BINDING_TOMBSTONE = 2,
};
/* What a path resolves to. This is the binding VALUE's discriminator, never
 * part of the key: one path is one node, and what an operation does depends on
 * the node's kind (insert/replace a group vs update/feed a complex). */
enum yetty_yvterm_rich_node_kind {
    YVTERM_NODE_GROUP = 0,
    YVTERM_NODE_COMPLEX = 1,
};
struct yetty_yvterm_rich_binding {
    uint8_t state;
    uint8_t node_kind;
    /* The addressable identity: a nested id PATH folded into 64 bits
     * (yetty_yvterm_group_key_fold). A flat top-level id is a one-segment
     * path; a nested node is its parent's key folded with the local id. */
    uint64_t group_key;
    struct yetty_yvterm_rich_handle block;
    /* Group slot for a GROUP node; record index for a COMPLEX node. */
    uint32_t slot;
    /* GROUP nodes: the slot occupant's generation at bind time. Group
     * slots are RECYCLED (rich-store group reuse), so a stale binding
     * whose path was never re-queried must not resolve to the slot's new
     * occupant — validation compares this against the live generation. */
    uint32_t group_generation;
};

