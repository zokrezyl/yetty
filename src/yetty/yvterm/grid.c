/* Line behind a slot id handed to the renderer: a real ring slot, or an
 * extended id (>= slot_count) minted by grid_view_window for archive rows —
 * those translate through the per-frame window_lines table into the
 * materialization cache. NULL for anything out of range. */
static struct yetty_yvterm_line *grid_slot_line(struct yetty_yvterm_grid *grid, uint32_t slot)
{
    struct yetty_yvterm_screen *screen = active_screen(grid);
    if (slot < screen->line_count) {
        return &screen->lines[slot];
    }
    uint32_t window_row = slot - screen->line_count;
    if (window_row < grid->window_count) {
        return grid->window_lines[window_row];
    }
    return NULL;
}

/* Resolve block `block_index` on the line behind `slot`. NULL when the slot
 * or index is out of range (or the handle went stale). */
static struct yetty_yvterm_rich_block *grid_slot_block(struct yetty_yvterm_grid *grid,
                                                       uint32_t slot, uint32_t block_index)
{
    struct yetty_yvterm_line *line = grid_slot_line(grid, slot);
    if (!line || block_index >= line->rich_block_count) {
        return NULL;
    }
    return yetty_yvterm_rich_store_resolve(&grid->rich_store, line->rich_blocks[block_index]);
}

/*===========================================================================
 * Screen-wide sorted render plan (paint-plan.h)
 *=========================================================================*/

/* The stamp a screen's plan must match: the sum of the store paint
 * generations it covers. Each generation is monotone, so the sum changes
 * whenever any constituent does. */
static uint64_t grid_paint_plan_stamp(const struct yetty_yvterm_grid *grid, int alternate)
{
    const uint64_t *generation = grid->rich_store.paint_generation;
    if (alternate) {
        return generation[YETTY_YVTERM_RICH_SCREEN_ALTERNATE];
    }
    return generation[YETTY_YVTERM_RICH_SCREEN_PRIMARY] +
           generation[YETTY_YVTERM_RICH_SCREEN_CACHE];
}

static int grid_paint_leaf_compare(const void *first_ptr, const void *second_ptr)
{
    const struct yetty_yvterm_paint_leaf *first = first_ptr;
    const struct yetty_yvterm_paint_leaf *second = second_ptr;
    if (first->paint_z != second->paint_z) {
        return first->paint_z < second->paint_z ? -1 : 1;
    }
    if (first->paint_sequence != second->paint_sequence) {
        return first->paint_sequence < second->paint_sequence ? -1 : 1;
    }
    if (first->record_ordinal != second->record_ordinal) {
        return first->record_ordinal < second->record_ordinal ? -1 : 1;
    }
    return 0;
}

/* Validate-or-rebuild the plan for `alternate` and hand it out. The walk
 * covers every resident block of the screen (plus the archive view cache
 * for primary) — visibility against the current rolling view is the per
 * frame walk's job, not the plan's. */
static struct yetty_ycore_void_result grid_paint_plan_ensure(
    struct yetty_yvterm_grid *grid, int alternate, const struct yetty_yvterm_paint_plan **out_plan)
{
    struct yetty_yvterm_paint_plan *plan = &grid->paint_plans[alternate ? 1 : 0];
    uint64_t stamp = grid_paint_plan_stamp(grid, alternate);
    if (plan->built && plan->built_stamp == stamp) {
        *out_plan = plan;
        return YETTY_OK_VOID();
    }
    plan->leaf_count = 0;
    struct yetty_yvterm_rich_store *store = &grid->rich_store;
    for (uint32_t slot = 0; slot < store->block_capacity; ++slot) {
        struct yetty_yvterm_rich_block *block = &store->blocks[slot];
        if (!block->in_use) {
            continue;
        }
        int covered = alternate ? block->screen == YETTY_YVTERM_RICH_SCREEN_ALTERNATE
                                : (block->screen == YETTY_YVTERM_RICH_SCREEN_PRIMARY ||
                                   block->screen == YETTY_YVTERM_RICH_SCREEN_CACHE);
        if (!covered) {
            continue;
        }
        for (uint32_t record_index = 0; record_index < block->record_count; ++record_index) {
            const struct yetty_yvterm_rich_record *record = &block->records[record_index];
            if (!record->alive || !record->render_leaf) {
                continue;
            }
            if (plan->leaf_count == plan->leaf_capacity) {
                uint32_t new_capacity = plan->leaf_capacity ? plan->leaf_capacity * 2u : 64u;
                struct yetty_yvterm_paint_leaf *grown = realloc(
                    plan->leaves, (size_t)new_capacity * sizeof(struct yetty_yvterm_paint_leaf));
                if (!grown) {
                    plan->built = 0; /* half-filled plan must not be served */
                    return YETTY_ERR(yetty_ycore_void, "yvterm paint plan: leaf table oom");
                }
                plan->leaves = grown;
                plan->leaf_capacity = new_capacity;
            }
            struct yetty_yvterm_paint_leaf *leaf = &plan->leaves[plan->leaf_count++];
            leaf->block.slot = slot;
            leaf->block.generation = block->generation;
            leaf->record_index = record_index;
            leaf->kind = record->kind;
            leaf->paint_z = record->paint_z;
            leaf->paint_sequence = record->paint_sequence;
            leaf->record_ordinal = record->record_ordinal;
        }
    }
    /* Keys are unique among alive records, so the unstable qsort still
     * yields exactly one order. */
    qsort(plan->leaves, plan->leaf_count, sizeof(struct yetty_yvterm_paint_leaf),
          grid_paint_leaf_compare);
    plan->built_stamp = stamp;
    plan->built = 1;
    plan->build_count++;
    *out_plan = plan;
    return YETTY_OK_VOID();
}

struct yetty_ycore_void_result yetty_yvterm_grid_paint_plan_current(
    struct yetty_yclass_object *grid_obj, const struct yetty_yvterm_paint_plan **out_plan)
{
    struct yetty_yvterm_grid_ptr_result grid_res = yetty_yvterm_grid_from(grid_obj);
    YETTY_RETURN_IF_ERR(yetty_ycore_void, grid_res, "yvterm paint_plan_current: from_obj");
    struct yetty_yvterm_grid *grid = grid_res.value;
    return grid_paint_plan_ensure(grid, grid->alt_screen ? 1 : 0, out_plan);
}

void yetty_yvterm_grid_paint_leaf_resolve(struct yetty_yclass_object *grid_obj,
                                          const struct yetty_yvterm_paint_leaf *leaf,
                                          const uint32_t **out_words, uint32_t *out_word_count,
                                          struct yetty_ydraw_complex **out_complex,
                                          uint32_t *out_span_rows, uint64_t *out_bottom_owner_row,
                                          int *out_alive, float *out_offset_x, float *out_offset_y)
{
    if (out_offset_x) {
        *out_offset_x = 0.0f;
    }
    if (out_offset_y) {
        *out_offset_y = 0.0f;
    }
    if (out_words) {
        *out_words = NULL;
    }
    if (out_word_count) {
        *out_word_count = 0u;
    }
    if (out_complex) {
        *out_complex = NULL;
    }
    if (out_span_rows) {
        *out_span_rows = 0u;
    }
    if (out_bottom_owner_row) {
        *out_bottom_owner_row = 0u;
    }
    if (out_alive) {
        *out_alive = 0;
    }
    struct yetty_yvterm_grid_ptr_result grid_res = yetty_yvterm_grid_from(grid_obj);
    if (YETTY_IS_ERR(grid_res)) {
        yetty_ycore_error_destroy(grid_res.error);
        return;
    }
    struct yetty_yvterm_rich_block *block =
        yetty_yvterm_rich_store_resolve(&grid_res.value->rich_store, leaf->block);
    if (!block || leaf->record_index >= block->record_count) {
        return;
    }
    struct yetty_yvterm_rich_record *record = &block->records[leaf->record_index];
    if (!record->alive) {
        return;
    }
    /* Accumulate the ancestor groups' translation offsets — the projection
     * input: rendering places this leaf at declared coords + this sum. */
    if (out_offset_x || out_offset_y) {
        float acc_x = 0.0f;
        float acc_y = 0.0f;
        uint32_t walk = record->group_slot;
        uint32_t guard = 0;
        while (walk != 0 && walk <= block->group_count && guard++ <= block->group_count) {
            const struct yetty_yvterm_rich_group *group = &block->groups[walk - 1u];
            acc_x += group->offset_x;
            acc_y += group->offset_y;
            walk = group->parent_slot;
        }
        if (out_offset_x) {
            *out_offset_x = acc_x;
        }
        if (out_offset_y) {
            *out_offset_y = acc_y;
        }
    }
    if (out_words) {
        *out_words = record->word_count ? block->arena + record->arena_offset : NULL;
    }
    if (out_word_count) {
        *out_word_count = record->word_count;
    }
    if (out_complex) {
        *out_complex = record->complex_runtime;
    }
    if (out_span_rows) {
        *out_span_rows = block->span_rows;
    }
    if (out_bottom_owner_row) {
        *out_bottom_owner_row = block->bottom_owner_row;
    }
    if (out_alive) {
        *out_alive = 1;
    }
}

/* Resolve the leaf's accumulated CLIP: the intersection of every ancestor
 * group's clip rect, expressed in block-content space (each group's local
 * clip shifts by that group's own offset plus everything above it). No
 * valid clip on the chain → out_valid 0 (unclipped). */
void yetty_yvterm_grid_paint_leaf_clip(struct yetty_yclass_object *grid_obj,
                                       const struct yetty_yvterm_paint_leaf *leaf, int *out_valid,
                                       float *out_x, float *out_y, float *out_w, float *out_h)
{
    if (out_valid) {
        *out_valid = 0;
    }
    struct yetty_yvterm_grid_ptr_result grid_res = yetty_yvterm_grid_from(grid_obj);
    if (YETTY_IS_ERR(grid_res)) {
        yetty_ycore_error_destroy(grid_res.error);
        return;
    }
    struct yetty_yvterm_rich_block *block =
        yetty_yvterm_rich_store_resolve(&grid_res.value->rich_store, leaf->block);
    if (!block || leaf->record_index >= block->record_count) {
        return;
    }
    const struct yetty_yvterm_rich_record *record = &block->records[leaf->record_index];
    uint32_t chain[64];
    uint32_t chain_count = 0;
    uint32_t walk = record->group_slot;
    uint32_t guard = 0;
    while (walk != 0 && walk <= block->group_count && guard++ <= block->group_count &&
           chain_count < 64u) {
        chain[chain_count++] = walk;
        walk = block->groups[walk - 1u].parent_slot;
    }
    /* Suffix offset sums (group's own offset + everything above it). */
    int have_clip = 0;
    float min_x = 0.0f, min_y = 0.0f, max_x = 0.0f, max_y = 0.0f;
    float suffix_x = 0.0f, suffix_y = 0.0f;
    for (uint32_t index = chain_count; index > 0; --index) {
        const struct yetty_yvterm_rich_group *group = &block->groups[chain[index - 1u] - 1u];
        suffix_x += group->offset_x;
        suffix_y += group->offset_y;
        if (!group->clip_valid) {
            continue;
        }
        float clip_min_x = group->clip_x + suffix_x;
        float clip_min_y = group->clip_y + suffix_y;
        float clip_max_x = clip_min_x + group->clip_w;
        float clip_max_y = clip_min_y + group->clip_h;
        if (!have_clip) {
            min_x = clip_min_x;
            min_y = clip_min_y;
            max_x = clip_max_x;
            max_y = clip_max_y;
            have_clip = 1;
        } else {
            if (clip_min_x > min_x) {
                min_x = clip_min_x;
            }
            if (clip_min_y > min_y) {
                min_y = clip_min_y;
            }
            if (clip_max_x < max_x) {
                max_x = clip_max_x;
            }
            if (clip_max_y < max_y) {
                max_y = clip_max_y;
            }
        }
    }
    if (!have_clip) {
        return;
    }
    if (max_x < min_x) {
        max_x = min_x;
    }
    if (max_y < min_y) {
        max_y = min_y;
    }
    if (out_valid) {
        *out_valid = 1;
    }
    if (out_x) {
        *out_x = min_x;
    }
    if (out_y) {
        *out_y = min_y;
    }
    if (out_w) {
        *out_w = max_x - min_x;
    }
    if (out_h) {
        *out_h = max_y - min_y;
    }
}

