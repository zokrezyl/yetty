/*===========================================================================
 * Default implementations registered on the base widget class.
 *=========================================================================*/

static struct yetty_ycore_void_result widget_default_constructor(struct yetty_ygui_object *obj)
{
    struct yetty_ygui_widget_data *wd = yetty_ygui_data_get(obj, yetty_ygui_widget_class_get());
    /* Zero rect (will be set by app via set_rect / layout pass). */
    wd->rect.min.x = 0;
    wd->rect.min.y = 0;
    wd->rect.max.x = 0;
    wd->rect.max.y = 0;
    wd->layout = yetty_ygui_layout_default();
    return YETTY_OK_VOID();
}

static struct yetty_ycore_void_result widget_default_destructor(struct yetty_ygui_object *obj)
{
    (void)obj;
    return YETTY_OK_VOID();
}

