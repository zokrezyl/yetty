/*
 * ygui-widget.c — base widget class.
 *
 * Every widget inherits from this class. It owns:
 *   - geometry: rect (absolute target pixels)
 *   - layout struct (flex / CSS authoring values)
 *
 * Declares public stubs for the widget-level virtual methods (on_press,
 * on_release, on_motion, emit_container, emit_body, paint) and provides
 * default implementations driven by the class's `figure_kind`:
 *
 *   - emit_container default: if figure_kind != 0, write CREATE_CHILD
 *     into the container records stream. Else no-op.
 *   - emit_body default: if figure_kind == 0, open CMD_GROUP in the
 *     ygrid body, invoke paint, close. Else no-op (the figure widget
 *     overrides emit_body to write figure-specific bytes).
 *   - paint default: no-op.
 *   - on_press / on_release / on_motion default: not-consumed (returns 0).
 */

#include "internal.h"

#include <yetty/yfigure/wire.h>
#include <string.h>

/*===========================================================================
 * Widget per-class data slice.
 *=========================================================================*/

struct yetty_ygui_widget_data {
    struct yetty_ycore_rectangle rect;
    struct yetty_ygui_layout layout;
};

/*===========================================================================
 * Method stubs — public addresses that serve as method ids.
 *
 * Each stub's signature is unique (different arg lists, different return
 * types), so the boilerplate is written out by hand per method rather
 * than auto-generated by macro.
 *=========================================================================*/

struct yetty_ycore_int_result yetty_ygui_widget_on_press(struct yetty_ygui_object *obj, float x,
                                                         float y, int button)
{
    static yetty_ygui_method_slot slot = YETTY_YGUI_METHOD_SLOT_UNDEFINED;
    if (slot == YETTY_YGUI_METHOD_SLOT_UNDEFINED) {
        slot = yetty_ygui_method_slot_get((yetty_ygui_method_id_t)yetty_ygui_widget_on_press);
    }
    if (!obj) {
        return YETTY_ERR(yetty_ycore_int, "yetty_ygui_widget_on_press: NULL obj");
    }
    yetty_ygui_impl_t impl = yetty_ygui_class_dispatch_lookup(obj->klass, slot);
    if (!impl) {
        return YETTY_OK(yetty_ycore_int, 0);
    }
    typedef struct yetty_ycore_int_result (*fn_t)(struct yetty_ygui_object *, float, float, int);
    return ((fn_t)impl)(obj, x, y, button);
}

