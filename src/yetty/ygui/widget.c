/* Default emit_container — true no-op on the base widget class.
 * Figure widget subclasses (yimage, yplot, …) override this to mint
 * their own receiver-side figure via yetty_ygui_emit_create_child
 * with their kind hardcoded. Primitive widgets don't touch the
 * container record stream. */
static struct yetty_ycore_void_result widget_default_emit_container(struct yetty_ygui_object *obj,
                                                                    struct yetty_ygui_emit_ctx *ctx)
{
    (void)obj;
    (void)ctx;
    return YETTY_OK_VOID();
}

/* Default emit_body — true no-op. The primitive_widget subclass
 * overrides this to dispatch to paint(); figure widgets override it
 * to ship their figure-specific bytes via yetty_ygui_emit_figure_body. */
static struct yetty_ycore_void_result widget_default_emit_body(struct yetty_ygui_object *obj,
                                                               struct yetty_ygui_emit_ctx *ctx)
{
    (void)obj;
    (void)ctx;
    return YETTY_OK_VOID();
}

/*===========================================================================
 * Layout setters / getters.
 *=========================================================================*/

struct yetty_ygui_layout yetty_ygui_layout_default(void)
{
    struct yetty_ygui_layout l = {0};
    l.direction = YETTY_YGUI_FLEX_ROW;
    l.justify = YETTY_YGUI_JUSTIFY_START;
    l.align = YETTY_YGUI_ALIGN_START;
    l.gap = 0;
    l.width = -1.0f;
    l.height = -1.0f;
    l.flex_grow = 0;
    l.flex_shrink = 0;
    l.min_width = -1.0f;
    l.max_width = -1.0f;
    l.min_height = -1.0f;
    l.max_height = -1.0f;
    l.absolute = 0;
    l.pos_x = 0.0f;
    l.pos_y = 0.0f;
    return l;
}

struct yetty_ycore_void_result yetty_ygui_widget_set_rect(struct yetty_ygui_object *obj,
                                                          struct yetty_ycore_rectangle rect)
{
    if (!obj) {
        return YETTY_ERR(yetty_ycore_void, "yetty_ygui_widget_set_rect: NULL obj");
    }
    struct yetty_ygui_widget_data *wd = yetty_ygui_data_get(obj, yetty_ygui_widget_class_get());
    wd->rect = rect;
    obj->dirty = 1;
    return YETTY_OK_VOID();
}

struct yetty_ycore_rectangle yetty_ygui_widget_rect(const struct yetty_ygui_object *obj)
{
    struct yetty_ycore_rectangle zero = {{0, 0}, {0, 0}};
    if (!obj) {
        return zero;
    }
    struct yetty_ygui_widget_data *wd =
        yetty_ygui_data_get((struct yetty_ygui_object *)obj, yetty_ygui_widget_class_get());
    return wd->rect;
}

struct yetty_ycore_void_result yetty_ygui_widget_layout_set(struct yetty_ygui_object *obj,
                                                            const struct yetty_ygui_layout *layout)
{
    if (!obj || !layout) {
        return YETTY_ERR(yetty_ycore_void, "yetty_ygui_widget_layout_set: NULL arg");
    }
    struct yetty_ygui_widget_data *wd = yetty_ygui_data_get(obj, yetty_ygui_widget_class_get());
    wd->layout = *layout;
    obj->dirty = 1;
    return YETTY_OK_VOID();
}

const struct yetty_ygui_layout *yetty_ygui_widget_layout_get(const struct yetty_ygui_object *obj)
{
    if (!obj) {
        return NULL;
    }
    struct yetty_ygui_widget_data *wd =
        yetty_ygui_data_get((struct yetty_ygui_object *)obj, yetty_ygui_widget_class_get());
    return &wd->layout;
}

